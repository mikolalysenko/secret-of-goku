#!/usr/bin/env node
// Merge reviewed proposals (.local/scene-graph/fixes/*.json) into
// engine/retail-dialogue.js: adaptations of retail text runs nobody had
// authored yet. Addresses that already have an authored entry are not merged;
// they are listed so the existing entry is edited in place instead (one
// source of truth per address).
//
//   node tools/scenes/apply-edits.mjs [--dry-run] [fixes/*.json…]
import fs from 'node:fs/promises';
import {parseEvent,encodeText,wrapText} from '../../engine/event-codec.js';
import {storyDialogue,soloDialogue} from '../../engine/story-dialogue.js';
import {partyDialogue} from '../../engine/scene-dialogue.js';
import {crisisDialogue} from '../../engine/frieza-crisis.js';
import {retailDialogue} from '../../engine/retail-dialogue.js';

const dry=process.argv.includes('--dry-run'),dir=process.argv.includes('--dir')?process.argv[process.argv.indexOf('--dir')+1]:'.local/scene-graph/fixes';
const files=process.argv.slice(2).filter((a,i,all)=>!a.startsWith('--')&&all[i-1]!=='--dir');
const sources=files.length?files:(await fs.readdir(dir)).filter(f=>f.endsWith('.json')).map(f=>`${dir}/${f}`);
const rom=await fs.readFile(process.env.SOM_ROM??'.local/rom/secret-of-mana-us.sfc');
// Existing entries keep their exact source line (and comment).
const existingLines=new Map((await fs.readFile('engine/retail-dialogue.js','utf8')).split('\n').map(l=>[l.match(/^\s*0x([0-9a-f]+):/i)?.[1],l]).filter(([k])=>k).map(([k,l])=>[parseInt(k,16),l]));
const merged=new Map(Object.entries(retailDialogue).map(([at,v])=>[Number(at),{value:v,event:null,reason:null,chunk:'existing',line:existingLines.get(Number(at))}]));
const manual=[],problems=[];
for(const file of sources){
  const {chunk,edits=[]}=JSON.parse(await fs.readFile(file,'utf8'));
  for(const e of edits){
    const at=parseInt(e.at,16),id=parseInt(e.event,16);
    if(!parseEvent(rom,id).ops.some(op=>op.op==='text'&&op.at===at)){problems.push(`${chunk} ${e.event} ${e.at}: not a text run of that event`);continue;}
    for(const v of[].concat(e.value))if(typeof v==='string'&&v){
      try{encodeText(v);}catch(error){problems.push(`${chunk} ${e.at}: ${error.message}`);}
      for(const line of wrapText(v).split('\n'))if(line.replace(/\{[0-3]\}/g,'XXXXXX').length>28)problems.push(`${chunk} ${e.at}: over 28 columns: ${line}`);
    }
    const value=e.table==='partyDialogue'&&Array.isArray(e.value)?e.value:e.value;
    if(e.table==='crisisDialogue'||at in storyDialogue||at in soloDialogue||at in partyDialogue||at in crisisDialogue){manual.push({chunk,...e});continue;}
    const prior=merged.get(at);
    if(prior&&prior.chunk!=='existing'&&JSON.stringify(prior.value)!==JSON.stringify(value)){problems.push(`${e.at}: conflicting proposals from ${prior.chunk} and ${chunk}`);continue;}
    merged.set(at,{value,event:id,reason:e.reason??'',chunk});
  }
}
const hex=n=>n.toString(16);
const body=[...merged].sort((a,b)=>a[0]-b[0]).map(([at,{value,event,reason,line}])=>line??
  `  0x${hex(at)}:${JSON.stringify(value)},${event!==null?` // ${hex(event)}${reason?': '+reason.replace(/\n/g,' '):''}`:''}`);
const source=`// Adaptations of retail text runs that no earlier pass had rewritten: Goku
// speaking Randi's lines, NPCs treating him as the sword's chosen boy or as
// weak, and party lines that break when a companion is absent. Keys are
// native US text-run addresses. A string applies to every party; an array is
// [solo, +Primm, +Popoi, both] where null keeps the line and "" removes it.
// Generated by tools/scenes/apply-edits.mjs from reviewed proposals; the
// compiler checks this table before the older story/party/solo tables.
export const retailDialogue={
${body.join('\n')}
};
`;
if(problems.length){console.error(`Not merged:\n${problems.join('\n')}`);process.exitCode=1;}
if(!dry&&!problems.length)await fs.writeFile('engine/retail-dialogue.js',source);
console.log(`${merged.size} retail entries${dry?' (dry run)':''}; ${manual.length} edits target existing authored entries:`);
for(const m of manual)console.log(`  [${m.chunk}] ${m.event} ${m.at} (${m.table}): ${JSON.stringify(m.value)}  — ${m.reason??''}`);
