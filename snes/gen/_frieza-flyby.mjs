// World-only flyby compiler. Browser poses/art are evaluated at build time;
// the 65816 selects one immutable OAM/upload/HDMA record each completed frame.
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {friezaFlybyPose,deathBallFlybyPose,deathBallTiming as timing} from '../../engine/frieza-flyby.js';
import {createDeathBallArt} from '../../engine/death-ball-art.js';
import {createOrbitEffects} from '../../engine/orbit-effects.js';
import {combustionCells,combustionFrames} from '../../engine/native-combustion-data.js';
import {decodeEffectFrame} from '../../engine/native-effects.js';
import {orbitVectors} from '../../engine/orbit-pixels.js';
import {drawFriezaSprite} from '../../engine/frieza-sprite.js';
import {readPng,encodeTile,quantize,nearest} from '../tools/gfx.mjs';
const hex=(v,n=4)=>'$'+(v&((n===2)?255:65535)).toString(16).padStart(n,'0');
const word=(a,v)=>a.push(v&255,(v>>8)&255);
const rgb=c=>[c&31,c>>5&31,c>>10&31];
const roots=[[96,200],[80,186],[112,184],[96,170],[70,176],[122,168],[96,150]];
const tiles=Array.from({length:40},(_,i)=>[0x130,0x150,0x190,0x1b0,0x1d0][i>>3]+(i&7)*2);
const attr=(tile,pal,flip=0)=>tile|0x3000|(pal<<9)|flip;
const visible=(x,y,s=16)=>x>-s&&x<256&&y>-s&&y<224;
export async function generateFlyby({repo,outDir,rom,xdata,atlas,palette}){
  const out=['; Generated by _frieza-flyby.mjs. Screen coordinates / exact browser clock.'];
  // Pack bank-local blobs. Pointers remain assembler expressions until xdata
  // placement; the records themselves use relocatable dl directives in FastROM.
  const banks=[]; let data=[],index=0;
  const flush=()=>{if(data.length){xdata(`frieza_flyby_${index}`,Uint8Array.from(data));banks.push(data.length);data=[];index++;}};
  const blob=bytes=>{if(bytes.length>0x8000)throw Error('flyby blob too large');if(data.length+bytes.length>0x8000)flush();const p={index,offset:data.length,expr:`!XDATA_FRIEZA_FLYBY_${index}+${data.length}`};data.push(...bytes);return p;};
  const assets=new Map();let tag=1;
  function asset(pixels,w,h,pal){
    const idx=Uint8Array.from(pixels,c=>c?nearest([0,...pal],c-1):0),bytes=[];
    for(let y=0;y<h;y+=8)for(let x=0;x<w;x+=8)bytes.push(...encodeTile(idx,w,x,y));
    const key=Buffer.from(bytes).toString('base64');
    if(!assets.has(key))assets.set(key,{ptr:blob(bytes),tag:tag++,row:w*4,rows:h/8});
    return assets.get(key);
  }
  const request=(a,tile,cache)=>({a,tile,cache});
  const fireCells=combustionCells.slice(0,21).map(f=>{const {rgba}=decodeEffectFrame(rom,f);return Uint16Array.from({length:256},(_,i)=>rgba[i*4+3]?1+(rgba[i*4]>>3)+((rgba[i*4+1]>>3)<<5)+((rgba[i*4+2]>>3)<<10):0);});
  const death=createDeathBallArt(rom),red=new Set();death(0,32,32,64,(_x,_y,c)=>red.add(c-1),{cinematic:true});
  const effectPal=[...new Set([...red,...fireCells.flatMap(c=>[...c].filter(Boolean).map(x=>x-1)),0x7fff])];
  if(effectPal.length>15)throw Error('flyby palette overflow '+effectPal.length);
  while(effectPal.length<15)effectPal.push(0);
  out.push('frieza_flyby_palette:','dw 0,'+effectPal.map(c=>hex(c)).join(','));
  // Canonical 16px Exploder cells, two rotations and OAM reflections. 40
  // cells fit the 160 tiles left in world regions B/C after Frieza's 8.
  const canonical=new Map(),burstAssets=[],burstPixels=[];
  const transform=(p,t,f)=>Uint16Array.from({length:256},(_,i)=>{let x=i&15,y=i>>4;if(f&1)x=15-x;if(f&2)y=15-y; if(t)[x,y]=[y,15-x];return p[y*16+x];});
  for(let ci=0;ci<21;ci++){for(let t=0;t<2;t++){
    let best=null;for(let f=0;f<4;f++){const p=transform(fireCells[ci],t,f),key=Buffer.from(p.buffer).toString('base64');if(!best||key<best.key)best={p,key,f};}
    if(!canonical.has(best.key)){canonical.set(best.key,burstAssets.length);burstAssets.push(asset(best.p,16,16,effectPal));burstPixels.push(best.p);}
  }}
  if(burstAssets.length!==40)throw Error('revisit flyby atlas layout: '+burstAssets.length);
  const burstGroups=[];
  for(let g=0;g<5;g++){const p=new Uint16Array(128*16);for(let i=0;i<8;i++)for(let y=0;y<16;y++)p.set(burstPixels[g*8+i].subarray(y*16,y*16+16),y*128+i*16);burstGroups.push(request(asset(p,128,16,effectPal),tiles[g*8],8+g));}
  const poseAssets=[];
  for(const f of [0,2,3]){
    const cell=atlas.cells[f],pieces=[]; // Fixed 3x3 grid: omit blank pieces.
    for(let y=0;y<48;y+=16)for(let x=0;x<48;x+=16){const p=Uint16Array.from({length:256},(_,i)=>cell[(y+(i>>4))*48+x+(i&15)]);if(p.some(Boolean))pieces.push({x:x-24,y:y-44,p});}
    if(pieces.length>8)throw Error('Frieza flyby needs more than 8 pieces');
    const pixels=new Uint16Array(pieces.length*16*16);pieces.forEach((p,i)=>{for(let y=0;y<16;y++)pixels.set(p.p.subarray(y*16,y*16+16),y*pieces.length*16+i*16);});
    poseAssets[f]={a:asset(pixels,pieces.length*16,16,palette),pieces};
  }
  const checker=(x,y)=>!(y&1)&&((x&1)===((y>>1)&1));
  const checkerCell=(surface,x,y,pal)=>asset(Uint16Array.from({length:1024},(_,i)=>checker(x+(i&31),y+(i>>5))?0x8000:surface?.[(y+(i>>5))*256+x+(i&31)]??0),32,32,pal);
  const empty=checkerCell(null,0,0,effectPal);
  const checkStatic=[request(empty,0x068,48)],checkOverrides=new Map();
  let checkSurface=new Uint16Array(256*224);
  const put=(x,y,c)=>{if(x>=0&&x<256&&y>=0&&y<224)checkSurface[y*256+x]=c;};
  const fp=friezaFlybyPose(timing.impact);drawFriezaSprite(atlas,fp.frame,fp.x,fp.y,put,{});
  let staticIndex=0;
  for(let y=0;y<224;y+=32)for(let x=0;x<256;x+=32){if(!Array.from({length:1024},(_,i)=>checkSurface[(y+(i>>5))*256+x+(i&31)]).some(Boolean))continue;
    const tile=[0x06c,0x0a8,0x0ac,0x0c0][staticIndex];if(tile===undefined)throw Error('checker Frieza exceeds reserved cells');
    checkStatic.push(request(checkerCell(checkSurface,x,y,palette),tile,49+staticIndex++));checkOverrides.set(y*256+x,attr(tile,7));
  }
  // Two 32px cells contain Goku, including the checker in their transparent
  // pixels. This avoids the PPU's 34-sliver limit during a full-screen checker.
  const gokuRequests=[],gokuFirst=[],gokuPals=[];
  for(let form=0;form<2;form++){
    const img=readPng(join(repo,'assets/sprites',form?'ssj.png':'goku.png')),hist=new Map(),cells=[];
    for(let f=0;f<4;f++){const p=Uint16Array.from({length:1024},(_,i)=>{const j=((128+(i>>5))*img.width+(form?36:40)*32+f*32+(i&31))*4;return img.data[j+3]?1+(img.data[j]>>3)+((img.data[j+1]>>3)<<5)+((img.data[j+2]>>3)<<10):0;});cells.push(p);for(const c of p)if(c&&c!==0x8000)hist.set(c-1,(hist.get(c-1)??0)+1);}
    const pal=[...quantize(hist,14),0x7fff];while(pal.length<15)pal.unshift(0);gokuPals.push(pal);
    for(let f=0;f<4;f++)for(let bob=0;bob<3;bob++)for(let bank=0;bank<3;bank++){
      const p=new Uint16Array(64*32);for(let y=0;y<32;y++)for(let x=0;x<64;x++){let c=0;const sx=x-(16+(bank-1)*2),sy=y-(3+bob);if(sx>=0&&sx<32&&sy>=0&&sy<32)c=cells[f][sy*32+sx];p[y*64+x]=checker(x+96,y+64)?0x8000:c;}
      gokuFirst.push(request(asset(p,64,32,pal),0x110,56));
      const middle=new Uint16Array(32*32);for(let y=0;y<32;y++)middle.set(p.subarray(y*64+16,y*64+48),y*32);
      gokuRequests.push(request(asset(middle,32,32,pal),0x112,56));
    }
  }
  out.push('frieza_flyby_goku_pal:');for(const p of gokuPals)out.push('dw 0,'+p.map(c=>hex(c)).join(','));
  // Compile painters' order, then drop the least visible pieces until every
  // line fits 30 slivers (two reserved for native world objects). Clusters
  // retain their exact centres, start times, native frames and quarter turns.
  const burstStats=[];
  function bursts(a){const pieces=[];
    for(const [i,[rx,ry]] of roots.entries()){const age=a-timing.impact-i*10;if(age<0||age>=74)continue;
      for(let j=0;j<9;j++){const t=age-j*4;if(t<0||t>=42)continue;const [vx,vy]=orbitVectors[j*6&15],r=j?8+Math.min(24,t):0,ox=rx+(vx*r>>8),oy=ry+(vy*r>>8),turn=j&3,flip=j&1;
        for(const part of combustionFrames.burst[t/6|0]){
          const sample=[];let x0=999,y0=999;
          for(let py=0;py<16;py++)for(let px=0;px<16;px++){const u=(part.x+px)*(flip?-1:1),v=part.y+py,x=ox+(turn===1?-v:turn===2?-u:turn===3?v:u),y=oy+(turn===1?u:turn===2?-v:turn===3?-u:v);x0=Math.min(x0,x);y0=Math.min(y0,y);sample.push([x,y,fireCells[part.cell][(part.flipY?15-py:py)*16+(part.flipX?15-px:px)]]);}
          if(!visible(x0,y0))continue;
          const p=new Uint16Array(256);for(const [x,y,c]of sample)p[(y-y0)*16+x-x0]=c;
          let found=null;for(let f=0;f<4;f++){const q=transform(p,0,f),k=Buffer.from(q.buffer).toString('base64');if(canonical.has(k)){found={id:canonical.get(k),f};break;}}
          if(!found)throw Error('burst transform absent');
          pieces.push({x:x0,y:y0,tile:attr(tiles[found.id],6,(found.f&1?0x4000:0)|(found.f&2?0x8000:0)),id:found.id,p});
        }
      }
    }
    pieces.reverse();const covered=new Set();let kept=[];
    for(const p of pieces){p.weight=0;for(let y=0;y<16;y++)for(let x=0;x<16;x++){const k=(p.y+y)*256+p.x+x;if(p.p[y*16+x]&&p.y+y>=0&&p.y+y<224){if(!covered.has(k))p.weight++;covered.add(k);}}if(p.weight)kept.push(p);}
    const before=kept.length;
    for(;;){const lines=new Uint8Array(224);for(const p of kept)for(let y=Math.max(0,p.y);y<Math.min(224,p.y+16);y++)lines[y]++;const crowded=lines.findIndex(n=>n>15);if(crowded<0&&kept.length<=78)break;
      let drop=-1;for(let i=0;i<kept.length;i++)if((crowded<0||kept[i].y<=crowded&&kept[i].y+16>crowded)&&(drop<0||kept[i].weight<kept[drop].weight))drop=i;kept.splice(drop,1);
    }
    burstStats.push({age:a,before,shown:kept.length});return kept;
  }
  const records=[],gokuLabels=[],gokuFirstLabels=[],solidColours=[];
  const pointer=(b,p)=>{word(b,p?.offset??0);b.push(p?.index??255);};
  function tableUpload(b,r){word(b,0x6000+r.tile*16);word(b,r.a.row);pointer(b,r.a.ptr);b.push(r.a.rows);word(b,r.cache*2);word(b,r.a.tag);}
  function record(sprites,uploads,win=null,col=null,mode=0){
    const b=[];word(b,sprites.length);word(b,uploads.length);pointer(b,win);pointer(b,col);word(b,mode);
    for(const p of sprites){word(b,(p.x&255)|((p.y&255)<<8));word(b,p.tile);}
    for(const r of uploads)tableUpload(b,r);return blob(b);
  }
  for(const [requests,labels] of [[gokuRequests,gokuLabels],[gokuFirst,gokuFirstLabels]])for(const r of requests){const b=[];tableUpload(b,r);labels.push(blob(b));}
  const htable=(rows)=>{const b=[];for(let y=0;y<224;){let n=1;while(n<127&&y+n<224&&rows[y+n].every((v,i)=>v===rows[y][i]))n++;b.push(n,...rows[y]);y+=n;}b.push(127,...rows[223],0);return blob(b);};
  // Four fixed 32px cells cover the first eight frames. Preload frame zero,
  // then upload only changed tile spans in each row, keeping vblank bounded.
  const checkerBursts=[],boxes=[{x:64,y:160},{x:96,y:160},{x:64,y:192},{x:96,y:192}];
  let previous=null;
  for(let a=timing.impact;a<timing.impact+8;a++){
    checkSurface=new Uint16Array(256*224);const fx=createOrbitEffects({cart:{data:rom}},{spriteLayer:{effects:{}}},put);
    for(const[i,[x,y]]of roots.entries()){const age=a-timing.impact-i*10;if(age>=0&&age<74)fx.burst(x,y,age,{large:true});}
    const packed=new Uint16Array(128*32),over=new Map(),uploads=[];
    for(const [i,{x,y}]of boxes.entries()){
      for(let py=0;py<32;py++)for(let px=0;px<32;px++)packed[py*128+i*32+px]=checker(x+px,y+py)?0x8000:checkSurface[(y+py)*256+x+px];
      over.set(y*256+x,attr(0x190+i*4,6));
    }
    if(previous)for(let row=0;row<4;row++){
      let lo=16,hi=-1;
      for(let tx=0;tx<16;tx++)for(let y=0;y<8;y++)for(let x=0;x<8;x++){const k=(row*8+y)*128+tx*8+x;if(packed[k]!==previous[k]){lo=Math.min(lo,tx);hi=Math.max(hi,tx);}}
      if(hi>=lo){const w=(hi-lo+1)*8,p=new Uint16Array(w*8);for(let y=0;y<8;y++)p.set(packed.subarray((row*8+y)*128+lo*8,(row*8+y)*128+(hi+1)*8),y*w);uploads.push(request(asset(p,w,8,effectPal),0x190+row*16+lo,60+row));}
    }
    checkerBursts.push({over,uploads,initial:[request(asset(packed.subarray(0,128*16),128,16,effectPal),0x190,58),request(asset(packed.subarray(128*16),128,16,effectPal),0x1b0,59)]});previous=packed;
  }
  for(let a=0;a<560;a++){
    let sprites=[],uploads=[],win=null,col=null,mode=0;
    const pose=friezaFlybyPose(a),ball=deathBallFlybyPose(a);
    let solid=0;
    if(pose.visible){const fr=poseAssets[pose.frame],tile=a===412?0x150:0x110;uploads.push(request(fr.a,tile,a===412?2:0));for(const [i,p]of fr.pieces.entries()){const x=pose.x+p.x,y=pose.y+p.y;if(visible(x,y))sprites.push({x,y,tile:attr(tile+i*2,7)});}}
    if(ball.visible){
      const size=Math.min(224,ball.size),surface=new Uint16Array(256*224);
      death(ball.frame,ball.x,ball.y,size,(x,y,c)=>{if(x>=0&&x<256&&y>=0&&y<224)surface[y*256+x]=c;},{cinematic:true});
      const sum=[0,0,0];let n=0;for(const c of surface)if(c){rgb(c-1).forEach((v,i)=>sum[i]+=v);n++;}solid=sum.map(v=>Math.round(v/(n||1))).reduce((v,c,i)=>v|(c<<(i*5)),0);
      if(size<=32){const pix=new Uint16Array(32*32);death(ball.frame,16,16,size,(x,y,c)=>pix[y*32+x]=c,{cinematic:true});
        // four cells laid out side by side for two DMA rows
        const packed=new Uint16Array(64*16);for(let q=0;q<4;q++)for(let y=0;y<16;y++)for(let x=0;x<16;x++)packed[y*64+q*16+x]=pix[((q>>1)*16+y)*32+(q&1)*16+x];
        uploads.push(request(asset(packed,64,16,effectPal),0x130,1));for(let q=0;q<4;q++){const x=ball.x-16+(q&1)*16,y=ball.y-16+(q>>1)*16;if(visible(x,y))sprites.push({x,y,tile:attr(0x130+q*2,6)});}
      }else{
        mode=1;const wr=[],cr=[];
        for(let y=0;y<224;y++){
          const sy=Math.floor((y-ball.y+size/2)*64/size),xs=[];for(let x=0;x<256;x++)if(surface[y*256+x]&&sy>=0&&sy<64&&((2*Math.floor((x-ball.x+size/2)*64/size)-63)**2+(2*sy-63)**2)<=57**2)xs.push(x);
          if(!xs.length){wr.push([255,0]);cr.push([0,0]);continue;}
          const l=xs[0],r=xs.at(-1),inner=xs.filter(x=>{const sx=Math.floor((x-ball.x+size/2)*64/size);return (2*sx-63)**2+(2*sy-63)**2<=55**2;});
          const sum=[0,0,0];for(const x of inner.length?inner:xs)rgb(surface[y*256+x]-1).forEach((v,i)=>sum[i]+=v);const mean=sum.map(v=>Math.round(v/(inner.length||xs.length)));
          wr.push([l,r]);cr.push([0x20|mean[0],0xc0|Math.round((mean[1]+mean[2])/2)]);
        }
        win=htable(wr);col=htable(cr);
        // Exact red art over Goku's body after the throw. This also masks
        // him precisely along the moving limb of the sphere.
        if(a>=timing.throw&&a<timing.impact){const packed=new Uint16Array(96*16);let any=false;
          for(let q=0;q<6;q++)for(let y=0;y<16;y++)for(let x=0;x<16;x++){const c=surface[(64+(q>>1)*16+y)*256+112+(q&1)*16+x];packed[y*96+q*16+x]=c;any ||=!!c;}
          if(any){uploads.push(request(asset(packed,96,16,effectPal),0x130,1));for(let q=0;q<6;q++)sprites.push({x:112+(q&1)*16,y:64+(q>>1)*16,tile:attr(0x130+q*2,6)});}
        }
      }
    }
    if(a>=timing.impact&&a<timing.impact+120){
      if(a<timing.impact+8){
        mode=2;const cb=checkerBursts[a-timing.impact],over=new Map([...checkOverrides,...cb.over]);uploads=a===timing.impact?[...checkStatic]:cb.uploads;
        over.set(64*256+96,attr(0x110,5));over.set(64*256+128,attr(0x114,5));sprites=[];
        for(let y=0;y<224;y+=32)for(let x=0;x<256;x+=32)sprites.push({x,y,tile:over.get(y*256+x)??attr(0x068,6)});
      }else{
        const ps=bursts(a);sprites.push(...ps);for(const g of new Set(ps.map(p=>p.id>>3))){
          if(a===timing.impact+8){
            const ids=ps.filter(p=>p.id>>3===g).map(p=>p.id),lo=Math.min(...ids),hi=Math.max(...ids),w=(hi-lo+1)*16,p=new Uint16Array(w*16);
            for(let i=lo;i<=hi;i++)for(let y=0;y<16;y++)p.set(burstPixels[i].subarray(y*16,y*16+16),y*w+(i-lo)*16);
            uploads.push(request(asset(p,w,16,effectPal),tiles[lo],8+g));
          }else uploads.push(burstGroups[g]);
        }
      }
    }
    if(a===352)uploads.push(request(poseAssets[2].a,0x150,2));
    if(a===350||a===351)uploads.push(checkerBursts[0].initial[a-350]);
    if(a>=200&&a<205)uploads.push(burstGroups[a-200]);
    // Static checker pictures use only world A's idle effect cells. They
    // are resident before the flash starts; the Goku cell stays untouched.
    if(a>=280&&a<280+checkStatic.length)uploads.push(checkStatic[a-280]);
    solidColours.push(solid);records.push(record(sprites,uploads,win,col,mode));
  }
  flush();
  // Relocatable pointer records live in the module's spare code/data space;
  // raw DMA/HDMA payload is exclusively xdata.
  out.push('frieza_flyby_colours:','dw '+solidColours.map(c=>hex(c)).join(','));
  out.push('frieza_flyby_frames:');for(const r of records)out.push('dl '+r.expr,'db 0');
  out.push('frieza_flyby_goku:');for(const r of gokuLabels)out.push('dl '+r.expr,'db 0');
  out.push('frieza_flyby_goku_first:');for(const r of gokuFirstLabels)out.push('dl '+r.expr,'db 0');
  out.push('frieza_flyby_banks:');for(let i=0;i<banks.length;i++)out.push(`dl !XDATA_FRIEZA_FLYBY_${i}`,'db 0');
  writeFileSync(join(outDir,'flyby.asm'),out.join('\n')+'\n');
  writeFileSync(join(outDir,'flyby-stats.json'),JSON.stringify({xdata:banks.reduce((a,b)=>a+b,0),assets:assets.size,burstStats},null,2));
}
