import {writeFileSync,mkdirSync} from 'node:fs';
import {join} from 'node:path';

// Native C2:1D7A's repeat/new-byte stream used by the Mana Beast. Decode
// once at build time; the runtime fast path checks all identifying inputs.
export async function generate({rom,outDir}){
  let p=0x15D22,remaining=72,current=0,previous=0;
  const out=[],read=()=>rom[p++];
  if(read()===0){while(remaining--)out.push(read());}
  else while(remaining>0){
    let control=read();
    for(let bit=0;bit<8&&remaining>0;bit++){
      const take=control&0x80;control=(control<<1)&255;
      const value=take?read():previous;
      previous=current;current=value;out.push(value);remaining--;
    }
  }
  if(p!==0x15D60||out.length!==72)throw Error('native Beast LZ stream changed');
  mkdirSync(outDir,{recursive:true});
  const lines=out.map((v,i)=>`${i%12===0?'\tdb ':''}$${v.toString(16).padStart(2,'0')}${i%12===11||i===out.length-1?'\n':','}`);
  writeFileSync(join(outDir,'data.asm'),'; Generated by snes/gen/core-lz.mjs.\ncore_lz_beast_data:\n'+lines.join(''));
}
