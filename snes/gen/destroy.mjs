// Data generator for the destroy module (snes/src/modules/destroy).
// Every table comes from the browser engine's JavaScript or the cartridge:
// exported constants are imported; constants that the engine keeps private
// inside a function are recovered by probing the exported functions and are
// asserted against them, so a change in the engine fails the build here
// instead of drifting silently. Output: dist/snes/gen/destroy/tables.asm.
import {writeFileSync,readFileSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';

const hex2=v=>'$'+(v&255).toString(16).toUpperCase().padStart(2,'0');
const hex4=v=>'$'+(v&0xffff).toString(16).toUpperCase().padStart(4,'0');
const fail=m=>{throw Error('destroy generator: '+m);};
const assert=(c,m)=>{if(!c)fail(m);};

export async function generate({rom,repo,outDir}){
  const engine=name=>import(pathToFileURL(join(repo,'engine',name)).href);
  const {createNativePlants}=await engine('native-plants.js');
  const {createNativeLocalFlight}=await engine('native-local-flight.js');
  const {createDungeonGeometry,dungeonGroups,dungeonAirTiles,dungeonSpecialScenes}=await engine('dungeon-geometry.js');
  const {palaceBraziers,brazierPart}=await engine('palace-braziers.js');
  const {kiBarriers,barrierTileEvents,barrierHitEvent,barrierFloorEvents}=await engine('native-barriers.js');
  const {breakableDoors}=await engine('breakable-doors.js');
  const {createNativeOrbs}=await engine('native-orbs.js');
  const {buildStoryEvents}=await engine('story-events.js');
  const {eventRange}=await engine('event-codec.js');
  const {shipMaps}=await engine('sandship-wreck.js');
  const word=a=>rom[a]|rom[a+1]<<8;
  const out=[];
  const emit=s=>out.push(s);
  const bytes=(label,arr,per=16)=>{
    if(label)emit(`${label}:`);
    for(let i=0;i<arr.length;i+=per)emit('\tdb '+Array.from(arr.slice(i,i+per),hex2).join(','));
  };
  const words=(label,arr,per=8)=>{
    if(label)emit(`${label}:`);
    for(let i=0;i<arr.length;i+=per)emit('\tdw '+Array.from(arr.slice(i,i+per),hex4).join(','));
  };
  emit('; Generated by snes/gen/destroy.mjs from engine/*.js and the cartridge. Do not edit.');
  let whiteTables=null;

  // -------------------------------------------------------------------------
  // Fake SnesJs-shaped machine for probing engine functions.
  const fake=(ram=new Uint8Array(0x20000),data=rom)=>({ram,cart:{data},frames:1000,ppu:{mode:1},
    cpu:{r:new Uint8Array(8),br:new Uint16Array(8),cyclesLeft:0,cycle(){}}});
  const headerFlags=map=>rom[0x80000+word(0x87000+map*2)+2];

  // -------------------------------------------------------------------------
  // Map pieces: placement extents (dungeon-geometry.js context()).
  function pieces(map){
    const start=0x80000+word(0x85000+map*2),end=0x80000+word(0x85002+map*2);
    if(end<=start||end-start>4000)return[];
    const list=[];let layer=0;
    for(let p=start;p<end;){
      const flag=rom[p];if(flag>=254){layer=flag===255?1:0;p++;continue;}
      if(p+4>=end)break;
      const id=rom[p+2]|(rom[p+3]&1)<<8|(rom[p+4]&1)<<9,bank=id<0xa3?0xd:id<0x206?0xe:id<0x300?0xf:0xc;
      const address=(bank<<16)+word(0xd0004+id*2);
      list.push({layer,flag,min:rom[p+1]>>4,max:rom[p+1]&15,x:rom[p+3]>>1,y:rom[p+4]>>1,w:(rom[address]>>1)+1,h:(rom[address+1]>>1)+1});
      p+=5;
    }
    return list;
  }
  // Union of always-visible pieces per layer when it is a rectangle from the
  // origin that contains every conditional piece; otherwise the map needs
  // the runtime piece walk (complex).
  function extents(map){
    const list=pieces(map),ext=[[0,0],[0,0]];let complex=false;
    for(let l=0;l<2;l++){
      const ps=list.filter(p=>p.layer===l);if(!ps.length)continue;
      const always=ps.filter(p=>p.min===0&&p.max===15),cond=ps.filter(p=>!(p.min===0&&p.max===15));
      if(!always.length){complex=true;continue;}
      const x1=Math.min(128,Math.max(...always.map(p=>p.x+p.w))),y1=Math.min(128,Math.max(...always.map(p=>p.y+p.h)));
      let holes=false;
      for(let y=0;y<y1&&!holes;y++)for(let x=0;x<x1;x++)if(!always.some(p=>y>=p.y&&y<p.y+p.h&&x>=p.x&&x<p.x+p.w)){holes=true;break;}
      if(holes||cond.some(p=>p.x+p.w>x1||p.y+p.h>y1))complex=true;
      ext[l]=[x1,y1];
    }
    return{ext,complex,count:list.length};
  }

  // -------------------------------------------------------------------------
  // Dungeon context: context() is non-null for maps in a dungeon family,
  // outside the special scenes and with a wall tileset (private set).
  const contextGroup=new Array(512).fill(0);
  {
    const ram=new Uint8Array(0x20000),g=createDungeonGeometry(fake(ram));
    for(let map=0;map<511;map++){
      ram[0xdc]=map&255;ram[0xdd]=map>>8;ram[0xc0]=0;ram[0xc1]=8;ram[0xc2]=0;ram[0xc3]=8;
      g.invalidate();const c=g.context();
      if(c)contextGroup[map]=dungeonGroups.indexOf(c.group)+1;
    }
  }
  // Brazier beam maps (native-plants.js brazierPolicy): a plain beam also
  // shatters braziers there. Probe with a header that reports tileset 23.
  // A copy of the cartridge whose map headers all report tileset 23.
  const tileset23=()=>{
    const data=new Uint8Array(0x90000);data.set(rom.subarray(0,0x90000));
    for(let map=0;map<512;map++){data[0x87000+map*2]=0x00;data[0x87001+map*2]=0x80;}
    data[0x88002]=23;   // every header pointer -> C8:8000, flags byte at +2
    return data;
  };
  const brazierBeamMaps=new Set();
  {
    const data=tileset23();
    for(let map=0;map<512;map++){
      const ram=new Uint8Array(0x20000);ram[0xdc]=map&255;ram[0xdd]=map>>8;
      const pattern=palaceBraziers[0];
      for(const id of pattern){ram.set([0x13,6,0,0],0x1b800+id*4);}ram.set([0x12,6,0,0],0x1b800+186*4);
      pattern.forEach((id,i)=>ram[0x10000+(2+(i>>1))*128+3+(i&1)]=id);
      const plants=createNativePlants(fake(ram,data),{canCut:()=>true});
      const n=plants.enqueueTiles([{tx:3,ty:2,layer:0}],{policy:'beam'}).length;
      if(n===6)brazierBeamMaps.add(map);else assert(n===0,'unexpected brazier probe result');
    }
    assert(brazierBeamMaps.size>0&&brazierBeamMaps.size<12,'brazier beam maps not found');
  }

  // -------------------------------------------------------------------------
  // Protected cells (dungeon-geometry.js protectedCell), recovered by probing
  // blocked() on synthetic maps. Asserted to have the two known shapes so a
  // new rule fails the build rather than being ignored.
  const protectedRules={joch:null,water:null};
  {
    const probe=(map,w,h,tileset,fn)=>{
      const ram=new Uint8Array(0x20000);ram[0xdc]=map&255;ram[0xdd]=map>>8;
      ram[0xc0]=(w*16)&255;ram[0xc1]=(w*16)>>8;ram[0xc2]=(h*16)&255;ram[0xc3]=(h*16)>>8;
      for(let i=0;i<0x8000;i++)ram[0x10000+i]=1;      // tile 1 everywhere (not cave void 5)
      ram.set([0x13,0,0,0],0x1b800+4);ram.set([0x13,0,0,0],0x1bc00+4);ram.set([0x13,0,0,0],0x1b800+70*4);
      const g=createDungeonGeometry(fake(ram));
      return fn(g,ram);
    };
    // Map 72 (Joch's room) at 64x64: every layer-0 tile except 70.
    protectedRules.joch=probe(72,64,64,0,(g,ram)=>{
      const t=(tx,ty,l,tile)=>{ram[0x10000+l*0x4000+ty*128+tx]=tile;return g.blocked({tx,ty,layer:l,tile,flags:0x13,behavior:0,code:0,replacement:0});};
      const a=t(10,10,0,1),b=t(10,10,0,70),c=t(10,10,1,1);
      return{map:72,w:64,h:64,layer:0,except:70,ok:a&&!b&&!c};
    });
    assert(protectedRules.joch.ok,'map 72 protection rule changed');
    const small=probe(72,60,64,0,g=>g.blocked({tx:10,ty:10,layer:0,tile:1,flags:0x13,behavior:0,code:0,replacement:0}));
    assert(!small,'map 72 protection must depend on its 64x64 layout');
    // Map 139 (Water Palace stairs): a rectangle minus two columns, layer 0.
    protectedRules.water=probe(139,40,72,0,g=>{
      const cells=[];
      for(let ty=0;ty<72;ty++)for(let tx=0;tx<40;tx++)if(g.blocked({tx,ty,layer:0,tile:1,flags:0x13,behavior:0,code:0,replacement:0}))cells.push([tx,ty]);
      const xs=cells.map(c=>c[0]),ys=cells.map(c=>c[1]);
      const r={map:139,x0:Math.min(...xs),x1:Math.max(...xs),y0:Math.min(...ys),y1:Math.max(...ys)};
      r.gap=[];for(let x=r.x0;x<=r.x1;x++)if(!cells.some(c=>c[0]===x))r.gap.push(x);
      r.count=cells.length;
      return r;
    });
    const w=protectedRules.water;
    assert(w.count===(w.x1-w.x0+1-w.gap.length)*(w.y1-w.y0+1)&&w.gap.length===2&&w.gap[1]===w.gap[0]+1,'map 139 protection shape changed');
    // The Water Palace cells are protected on both layers.
    const layer1=probe(139,40,72,0,g=>{let n=0;for(let ty=0;ty<72;ty++)for(let tx=0;tx<40;tx++)if(g.blocked({tx,ty,layer:1,tile:1,flags:0x13,behavior:0,code:0,replacement:0}))n++;return n;});
    assert(layer1===w.count,'map 139 protection must cover both layers');
  }

  // -------------------------------------------------------------------------
  // The live map size ($C0/$C2) is the first placed piece's size (checked
  // against all 370 native-loaded gameplay maps). Inside the planner's
  // interior ([1,W-2] x [1,H-2]) every dungeon map's visible placement, for
  // any story flags, is exactly the rectangle of its always-visible pieces,
  // so the runtime placement test is two compares.
  function firstPieceSize(map){
    const list=pieces(map);return list.length?[Math.min(128,list[0].w),Math.min(128,list[0].h)]:[0,0];
  }
  for(let map=0;map<511;map++){
    if(!contextGroup[map])continue;
    const list=pieces(map),[W,H]=firstPieceSize(map),{ext}=extents(map);
    for(let l=0;l<2;l++){
      const always=list.filter(p=>p.layer===l&&p.min===0&&p.max===15),cond=list.filter(p=>p.layer===l&&!(p.min===0&&p.max===15));
      const inRect=(x,y)=>x<ext[l][0]&&y<ext[l][1];
      for(let y=1;y<H-1;y++)for(let x=1;x<W-1;x++){
        const covered=always.some(p=>y>=p.y&&y<p.y+p.h&&x>=p.x&&x<p.x+p.w);
        assert(covered===inRect(x,y),`map ${map} layer ${l}: unconditional placement is not a rectangle at ${x},${y}`);
        assert(!cond.some(p=>y>=p.y&&y<p.y+p.h&&x>=p.x&&x<p.x+p.w)||inRect(x,y),`map ${map} layer ${l}: conditional piece outside the rectangle at ${x},${y}`);
      }
    }
  }
  // The planner never needs the cave-void analysis: tileset 10's black
  // metatile 5 is solid (height 3), so it is neither a floor nor a wall
  // whatever its protection (collision tables C0:B0000 / B0:0400).
  {
    const type=rom[0xb0400+10*384+5];
    assert((rom[0xb0000+type*4]&7)===3,'tileset 10 metatile 5 is no longer solid');
  }

  // Maps with the Sandship deck rail (scenery replacement), from the probe below.
  const railMaps=[];
  for(const map of shipMaps.concat([97,100])){
    const ram=new Uint8Array(0x20000);ram[0xdc]=map&255;ram[0xdd]=map>>8;ram[0xc1]=4;ram[0xc3]=4;
    ram.set([0x13,0,0,0],0x1b800+122*4);ram.set([0x01,0,0,0],0x1b800+1*4);
    for(let y=0;y<64;y++)for(let x=0;x<64;x++)ram[0x10000+y*128+x]=1;
    const lf=createNativeLocalFlight(fake(ram),{});
    let found=false;
    for(let ty=1;ty<20&&!found;ty++)for(let tx=0;tx<40&&!found;tx++){
      ram[0x10000+ty*128+tx]=122;
      if(lf.breakScenery({tx,ty,layer:0,tile:122,flags:0x13,behavior:0,code:0,replacement:0})!==null)found=true;
      ram[0x10000+ty*128+tx]=1;
    }
    if(found)railMaps.push(map);
  }

  // -------------------------------------------------------------------------
  // Map info: 512 x 8 bytes.
  //  +0 header flags (tileset | $40 layer-0 metatile+192 | $80 layer-1 +192)
  //  +1 dungeon family index+1 when the demolition planner applies, else 0
  //  +2 bits: 0 brazier-beam map, 1 Sandship map, 2 complex placement,
  //     3 Joch protection, 4 Water Palace protection, 5 ki barrier,
  //     6 breakable-door map, 7 scenery replacements possible
  //  +3 first ki-barrier record index or $FF
  //  +4..7 placed extents (cells): layer 0 x1,y1, layer 1 x1,y1
  const barrierList=[...kiBarriers].map((b,i)=>({...b,order:i})).sort((a,b)=>a.map-b.map||a.order-b.order);
  // kiBarriers.find() takes the first match in declaration order; keep that
  // order within a map.
  const doorMaps=new Set(breakableDoors.flatMap(d=>d.maps));
  const mapInfo=[];let complexDungeons=[];
  for(let map=0;map<512;map++){
    const valid=map<511;
    const flags=headerFlags(map);
    const{ext,complex}=valid?extents(map):{ext:[[0,0],[0,0]],complex:false};
    let bits=0;
    if(brazierBeamMaps.has(map))bits|=1;
    if(shipMaps.includes(map))bits|=2;
    if(complex)bits|=4;
    if(map===protectedRules.joch.map)bits|=8;
    if(map===protectedRules.water.map)bits|=16;
    const first=barrierList.findIndex(b=>b.map===map);
    if(first>=0)bits|=32;
    if(doorMaps.has(map))bits|=64;
    // Scenery replacements can apply (carved heads, vines, the deck rail).
    if([1,7].includes(flags&63)||railMaps.includes(map))bits|=128;
    if(complex&&contextGroup[map])complexDungeons.push(map);
    mapInfo.push(flags,contextGroup[map],bits,first>=0?first:255,ext[0][0],ext[0][1],ext[1][0],ext[1][1]);
  }
  bytes('destroy_map_info',mapInfo,8);

  // -------------------------------------------------------------------------
  // Metatile classes. Air: dungeonAirTiles. Floor exclusions: blankZero
  // (metatile 0 is not a floor in these tilesets) and the Fire Palace window
  // recesses, both private to dungeon-geometry.js, recovered through floor().
  const air=new Uint8Array(32*64);
  for(const[ts,set]of Object.entries(dungeonAirTiles))for(const meta of set){assert(meta<512,'air meta range');air[Number(ts)*64+(meta>>3)]|=1<<(meta&7);}
  bytes('destroy_air_bits',air);
  const blankZero=new Uint8Array(32),falseFloor=new Uint8Array(64);
  {
    const g=createDungeonGeometry(fake());
    const walk={flags:0x01,behavior:0,code:0,replacement:0};
    for(let ts=0;ts<32;ts++){
      if(!g.floor({...walk,tile:0,layer:0},{tileset:ts,flags:0}))blankZero[ts]=1;
      assert(g.floor({...walk,tile:0,layer:1},{tileset:ts,flags:0})===!blankZero[ts],'blankZero must not depend on layer');
      for(let tile=1;tile<256;tile++)for(const layer of[0,1]){
        const f=g.floor({...walk,tile,layer},{tileset:ts,flags:0});
        if(f)continue;
        const decoration=ts===23&&layer===0&&brazierPart(tile)>=0;
        if(decoration)continue;
        assert(ts===23&&layer===0,`unexpected floor exclusion ts${ts} L${layer} tile ${tile}`);
        falseFloor[tile>>3]|=1<<(tile&7);
      }
      // The window recesses use metatile numbers: check the +192 bank too.
      for(let tile=0;tile<256;tile++){
        const meta=tile+192,f=g.floor({...walk,tile,layer:0},{tileset:ts,flags:0x40});
        const decoration=ts===23&&brazierPart(tile)>=0,blank=meta===0;
        if(!f&&!decoration&&!blank)assert(false,`unexpected high floor exclusion ts${ts} meta ${meta}`);
      }
    }
  }
  bytes('destroy_blank_zero',blankZero);
  bytes('destroy_false_floor',falseFloor);

  // -------------------------------------------------------------------------
  // Braziers (palace-braziers.js).
  const part=new Uint8Array(256).fill(255);
  for(let id=0;id<256;id++){const p=brazierPart(id);if(p>=0)part[id]=p;}
  bytes('destroy_brazier_part',part);
  assert(palaceBraziers.every(p=>p.length===6),'brazier patterns are 2x3');
  bytes('destroy_brazier_patterns',palaceBraziers.flat(),6);
  emit(`!DESTROY_BRAZIER_PATTERNS = ${palaceBraziers.length}`);
  {
    // Replacement tile and tileset, recovered from the plants pipeline.
    const data=tileset23();
    const ram=new Uint8Array(0x20000);
    palaceBraziers[0].forEach(id=>ram.set([0x13,6,0,0],0x1b800+id*4));
    palaceBraziers[0].forEach((id,i)=>ram[0x10000+(2+(i>>1))*128+3+(i&1)]=id);
    const plants=createNativePlants(fake(ram,data),{canCut:()=>true});
    const queued=plants.enqueueTiles([{tx:3,ty:2,layer:0}],{policy:'super-beam'});
    assert(queued.length===6&&queued.every(q=>q.replacement===queued[0].replacement),'brazier replacement probe');
    emit(`!DESTROY_BRAZIER_TILE = ${queued[0].replacement}`);
    emit(`!DESTROY_BRAZIER_TILESET = 23`);
  }

  // -------------------------------------------------------------------------
  // Scenery replacements (native-local-flight.js breakScenery).
  const vines=new Uint8Array(64);let vineTile=null,headTile=null,headSum=null;const heads=[];
  {
    const ram=new Uint8Array(0x20000);
    const lf=createNativeLocalFlight(fake(ram),{});
    const mapWithTileset=ts=>{for(let m=0;m<511;m++)if((headerFlags(m)&63)===ts&&!(headerFlags(m)&64))return m;return -1;};
    const m7=mapWithTileset(7),m1=mapWithTileset(1);
    assert(m7>=0&&m1>=0,'scenery probe maps');
    ram[0xdc]=m7&255;ram[0xdd]=m7>>8;
    for(let tile=0;tile<256;tile++){
      const r=lf.breakScenery({tx:5,ty:5,layer:0,tile,flags:0x13,behavior:0,code:0,replacement:0});
      if(r===null)continue;
      vines[tile>>3]|=1<<(tile&7);
      assert(vineTile===null||vineTile===r,'one vine replacement');vineTile=r;
      assert(lf.breakScenery({tx:5,ty:5,layer:1,tile,flags:0x13,behavior:0,code:0,replacement:0})===null,'vines are layer 0 only');
      assert(lf.breakScenery({tx:5,ty:5,layer:0,tile,flags:0x13,behavior:0,code:0xc8,replacement:0})===null,'vines have no cut code');
    }
    ram[0xdc]=m1&255;ram[0xdd]=m1>>8;
    for(let tile=0;tile<256;tile++)for(const replacement of[343-tile]){
      if(replacement<0||replacement>255)continue;
      const r=lf.breakScenery({tx:5,ty:5,layer:0,tile,flags:0x13,behavior:0,code:0xc1,replacement});
      if(r===null)continue;
      heads.push(tile);assert(headTile===null||headTile===r,'one head replacement');headTile=r;headSum=tile+replacement;
      assert(lf.breakScenery({tx:5,ty:5,layer:0,tile,flags:0x13,behavior:0,code:0xc1,replacement:(replacement+1)&255})===null,'heads need their twin');
    }
    assert(vineTile!==null&&heads.length===2&&headTile!==null,'scenery probe');
    // The flag bit (metatile +192) moves both ids out of range.
  }
  bytes('destroy_vine_bits',vines);
  emit(`!DESTROY_VINE_TILESET = 7`);
  emit(`!DESTROY_VINE_TILE = ${vineTile}`);
  emit(`!DESTROY_HEAD_TILESET = 1`);
  emit(`!DESTROY_HEAD_A = ${heads[0]}`);
  emit(`!DESTROY_HEAD_B = ${heads[1]}`);
  emit(`!DESTROY_HEAD_SUM = ${headSum}`);
  emit(`!DESTROY_HEAD_TILE = ${headTile}`);
  // Sandship deck rail: probe the cells, maps and replacement.
  {
    const rail=[];
    for(const map of shipMaps.concat([97,100])){
      const ram=new Uint8Array(0x20000);ram[0xdc]=map&255;ram[0xdd]=map>>8;ram[0xc1]=4;ram[0xc3]=4;
      ram.set([0x13,0,0,0],0x1b800+122*4);ram.set([0x01,0,0,0],0x1b800+1*4);
      const lf=createNativeLocalFlight(fake(ram),{});
      for(let y=0;y<64;y++)for(let x=0;x<64;x++)ram[0x10000+y*128+x]=1;
      for(let ty=1;ty<20;ty++)for(let tx=0;tx<40;tx++){
        ram[0x10000+ty*128+tx]=122;
        const r=lf.breakScenery({tx,ty,layer:0,tile:122,flags:0x13,behavior:0,code:0,replacement:0});
        ram[0x10000+ty*128+tx]=1;
        if(r!==null)rail.push({map,tx,ty,r});
      }
    }
    const maps=[...new Set(rail.map(c=>c.map))],ys=[...new Set(rail.map(c=>c.ty))],xs=rail.map(c=>c.tx);
    assert(maps.length===2&&ys.length===1&&new Set(rail.map(c=>c.r)).size===1,'ship rail probe');
    const x0=Math.min(...xs),x1=Math.max(...xs);
    assert(rail.length===2*(x1-x0+1),'ship rail columns');
    emit(`!DESTROY_RAIL_MAP_A = ${maps[0]}`);
    emit(`!DESTROY_RAIL_MAP_B = ${maps[1]}`);
    emit(`!DESTROY_RAIL_ROW = ${ys[0]}`);
    emit(`!DESTROY_RAIL_X0 = ${x0}`);
    emit(`!DESTROY_RAIL_X1 = ${x1}`);
    emit(`!DESTROY_RAIL_TILE = 122`);
    emit(`!DESTROY_RAIL_REPLACEMENT = ${rail[0].r}`);
  }

  // -------------------------------------------------------------------------
  // Protected cells.
  emit(`!DESTROY_JOCH_MAP = ${protectedRules.joch.map}`);
  emit(`!DESTROY_JOCH_SIZE = ${protectedRules.joch.w}`);
  emit(`!DESTROY_JOCH_KEEP = ${protectedRules.joch.except}`);
  const w=protectedRules.water;
  emit(`!DESTROY_WATER_MAP = ${w.map}`);
  emit(`!DESTROY_WATER_X0 = ${w.x0}`);
  emit(`!DESTROY_WATER_X1 = ${w.x1}`);
  emit(`!DESTROY_WATER_Y0 = ${w.y0}`);
  emit(`!DESTROY_WATER_Y1 = ${w.y1}`);
  emit(`!DESTROY_WATER_GAP = ${w.gap[0]}`);

  // -------------------------------------------------------------------------
  // Barrier event scripts. Story-authored barrier events occupy retail END
  // slots; the module runs these compiled copies directly when the event
  // table still points at the retail END byte (no story routing installed).
  const storyIds=new Set();
  for(const b of kiBarriers)if(b.event!==undefined)storyIds.add(b.event);
  for(const d of breakableDoors)if(d.prepareEvent)storyIds.add(d.prepareEvent);
  const variants=[0,1,2,3].map(mask=>buildStoryEvents(rom,mask)),crisis=buildStoryEvents(rom,0,{crisis:true});
  const scripts=[];
  for(const id of[...storyIds].sort((a,b)=>a-b)){
    const{start,end}=eventRange(rom,id);
    const authored=variants[0].get(id);
    if(!authored)continue; // a retail event: dispatched through the native table
    assert(end-start===1&&rom[start]===0,`event ${id.toString(16)} is not a retail END slot`);
    for(const v of[...variants,crisis])assert(JSON.stringify(v.get(id))===JSON.stringify(authored),`event ${id.toString(16)} differs by party/crisis`);
    scripts.push({id,start,bytes:authored});
  }
  // (The breakable doors' opened trigger events are routed by story on the
  // DOOR_* queries this module answers.)
  emit('destroy_scripts:');
  for(const s of scripts)bytes(`destroy_script_${s.id.toString(16)}`,s.bytes);
  // Script table: event id, retail slot (C9/CA address), long pointer.
  emit('destroy_script_table:');
  for(const s of scripts){
    const bank=s.id<0x400?0xc9:0xca,addr=s.start&0xffff;
    assert((s.start>>16)===(bank&0x3f),'retail slot bank');
    emit(`\tdw ${hex4(s.id)},${hex4(addr)} : dl destroy_script_${s.id.toString(16)} : db ${hex2(bank)}`);
  }
  emit('\tdw $FFFF');

  // -------------------------------------------------------------------------
  // Ki barriers (native-barriers.js kiBarriers), sorted by map; 20 bytes:
  //  map.w x.w y.w w.w h.w flag min event.w opts door react cutx cuty pad
  //  opts: 1 beamOnly, 2 repeatUntilOpen, 4 door, 8 cut (legacy repair)
  const reactions=['none'];
  const react=id=>{let i=reactions.indexOf(id);if(i<0){reactions.push(id);i=reactions.length-1;}return i;};
  const doorIndex=id=>breakableDoors.findIndex(d=>d.id===id);
  emit('destroy_barriers:');
  for(const b of barrierList){
    const[x,y,wd,ht]=b.rect;
    const opts=(b.beamOnly?1:0)|(b.repeatUntilOpen?2:0)|(b.door?4:0)|(b.cut?8:0);
    const door=b.door?doorIndex(b.door):255;assert(!b.door||door>=0,'barrier door');
    emit(`\tdw ${b.map},${x},${y},${wd},${ht} : db ${hex2(b.flag)},${b.min} : dw ${hex4(b.event??0xffff)} : db ${hex2(opts)},${hex2(door)},${react(b.id)},${hex2(b.cut?.[0]??0)},${hex2(b.cut?.[1]??0)},0`);
  }
  emit('\tdw $FFFF');
  emit(`!DESTROY_BARRIER_SIZE = 20`);

  // Hit-tile events (barrierHitEvent): source, map ($FFFF any), event.
  emit('destroy_hit_events:');
  const sources=[...new Set([...barrierTileEvents.keys(),0x1af])].sort((a,b)=>a-b);
  for(const source of sources){
    const results=new Map();
    for(let map=0;map<512;map++){const e=barrierHitEvent(map,source);if(e!==null&&e!==undefined)results.set(map,e);}
    const values=new Set(results.values());
    if(results.size===512&&values.size===1)emit(`\tdw ${hex4(source)},$FFFF,${hex4([...values][0])}`);
    else for(const[map,e]of results)emit(`\tdw ${hex4(source)},${hex4(map)},${hex4(e)}`);
  }
  emit('\tdw $FFFF');
  // Floor (pressure plate) events.
  emit('destroy_floor_events:');
  for(const[source,event]of[...barrierFloorEvents].sort((a,b)=>a[0]-b[0]))emit(`\tdw ${hex4(source)},${hex4(event)}`);
  emit('\tdw $FFFF');
  // The Grand Palace button combination (native-barriers.js nativeTile).
  emit('!DESTROY_COMBO_LO = $565');
  emit('!DESTROY_COMBO_HI = $568');
  emit('!DESTROY_COMBO_FLAG = $42');
  emit('!DESTROY_COMBO_STAGE = 3');
  {
    // Assert the combination rule against barrierHitEvent's table.
    for(let s=0x565;s<=0x568;s++)assert(barrierTileEvents.get(s)===0x56b,'palace combination events');
  }
  emit(`!DESTROY_REACT_COMBO = ${react('palace-combination')}`);

  // Breakable doors: 16 bytes each:
  //  flag openAt prepare.w mapA.w mapB.w evA.w evB.w react prepIsScript pad pad
  emit('destroy_doors:');
  breakableDoors.forEach((d,i)=>{
    assert(d.maps.length>=1&&d.maps.length<=2&&d.events.size<=2,'door shape');
    const ev=[...d.events.keys()];
    emit(`\tdb ${hex2(d.flag)},${d.openAt} : dw ${hex4(d.prepareEvent??0)},${hex4(d.maps[0])},${hex4(d.maps[1]??0xffff)},${hex4(ev[0]??0xffff)},${hex4(ev[1]??0xffff)} : db ${react(d.id)},0,0,0`);
  });
  emit(`!DESTROY_DOORS = ${breakableDoors.length}`);
  breakableDoors.forEach((d,i)=>emit(`!DESTROY_DOOR_${d.id.toUpperCase().replace(/-/g,'_')} = ${i}`));
  // Watts's shortcut entrance (native-story.js storyRead: the range byte at
  // C8:5A8E reads $0F once the gaia-shortcut door broke): the map-73 piece
  // gated by the door's flag. The loader hook keys on its record address.
  {
    const door=breakableDoors.find(d=>d.id==='gaia-shortcut');
    assert(door&&door.maps.length===1,'gaia shortcut door');
    const map=door.maps[0],start=0x80000+word(0x85000+map*2),end=0x80000+word(0x85002+map*2);
    const records=[];
    for(let p=start;p<end;){if(rom[p]>=254){p++;continue;}records.push(p);p+=5;}
    const gated=records.filter(p=>rom[p]===door.flag);
    assert(gated.length===1&&gated[0]+1===0x85a8e,'the shortcut piece record moved (native-story.js reads C8:5A8E)');
    const range=rom[gated[0]+1];
    assert((range>>4)===door.openAt&&(range&15)===15,'shortcut piece range');
    emit(`!DESTROY_SHORTCUT_LO = ${hex2(gated[0]&255)}`);
    emit(`!DESTROY_SHORTCUT_HI = ${hex2(gated[0]>>8&255)}`);
  }

  // -------------------------------------------------------------------------
  // Crystal orbs: event -> spell byte for $E181 (native-orbs.js describe()).
  emit('destroy_orb_events:');
  {
    const ram=new Uint8Array(0x20000),orbs=createNativeOrbs(fake(ram),{options:{enabled:true}});
    let n=0;
    for(let ev=1;ev<0x800;ev++){
      const base=0xe600;ram[base+0x3e]=ev&255;ram[base+0x3f]=ev>>8;
      const d=orbs.describe({species:0x55,active:true,index:3,base});
      if(!d)continue;
      emit(`\tdw ${hex4(ev)} : db ${hex2(d.spell)}`);n++;
    }
    assert(n>=8,'orb events');
  }
  emit('\tdw $FFFF');

  // Dungeon family names (reaction ids for the first breach per family).
  dungeonGroups.forEach(g=>react(`dungeon-wall-${g.id}`));
  emit(`!DESTROY_REACT_WALL_BASE = ${react('dungeon-wall-'+dungeonGroups[0].id)}`);
  emit(`!DESTROY_DUNGEONS = ${dungeonGroups.length}`);
  // Reaction ids for other modules (radio): index -> name.
  emit('; reactions: '+reactions.map((r,i)=>`${i}=${r}`).join(' '));
  for(const ship of shipMaps)assert(ship<512,'ship map range');
  emit(`; complex-placement dungeon maps (runtime piece walk): ${complexDungeons.join(',')}`);
  emit(`; special scenes excluded from demolition: ${[...dungeonSpecialScenes.keys()].join(',')}`);

  // -------------------------------------------------------------------------
  // Sandship runtime (engine/sandship.js createSandship, sandship-wreck.js).
  // Exported constants are imported; the ones the engine keeps private in
  // its module scope are read from the source text with exact patterns, so a
  // changed constant fails here instead of drifting.
  {
    const ss=await engine('sandship.js'),sw=await engine('sandship-wreck.js');
    const text=name=>readFileSync(join(repo,'engine',name),'utf8');
    const ssText=text('sandship.js'),swText=text('sandship-wreck.js');
    const grab=(src,re,what)=>{const m=src.match(re);assert(m,`sandship: ${what} not found`);return m;};
    const [,geshtar,deck,decksA,decksB,kitchen,cabin]=grab(ssText,/const geshtar=(\d+),deck=(\d+),decks=\[(\d+),(\d+)\],kitchen=(\d+),cabin=(\d+);/,'actors and rooms').map(Number);
    const [,dunes,leftDunes]=grab(ssText,/const dunes=(\d+),leftDunes=(\d+);/,'dunes').map(Number);
    const [,breakLimit,endingHex]=grab(ssText,/const breakLimit=(\d+),ending=0x([0-9a-f]+),/,'break limit');
    const fled=grab(swText,/const fled=new Set\(\[([\d,]+)\]\);/,'fled species')[1].split(',').map(Number);
    const monsters=grab(swText,/const monsters=\[([\d,]+)\];/,'monster species')[1].split(',').map(Number);
    const counts=Object.fromEntries(grab(swText,/const monsterCount=\{([\d:,]+)\};/,'monster counts')[1].split(',').map(e=>e.split(':').map(Number)));
    const escapeDoor=parseInt(grab(swText,/const escapeDoor=0x([0-9a-f]+);/,'escape door')[1],16);
    // The placement order hash, evaluated from its own source line.
    const hashSrc=grab(swText,/const hash=\(a,b=0\)=>\{[^\n]*\};/,'hash')[0];
    const hash=new Function(hashSrc+'return hash;')();
    assert(ss.holdMaps.length===3&&ss.shipDoors[0]===0x1a0&&ss.shipDoors.length===32,'hold maps / ship doors');
    assert(monsters.length===2&&fled.length===5,'wreck actor sets');
    assert(sw.alarmSong.length===4&&sw.alarmSong[0]===1,'alarm song command');
    emit('; Sandship runtime');
    emit(`!SS_DECK = ${deck}`);emit(`!SS_DECK_A = ${decksA}`);emit(`!SS_DECK_B = ${decksB}`);
    emit(`!SS_KITCHEN = ${kitchen}`);emit(`!SS_CABIN = ${cabin}`);emit(`!SS_GESHTAR = ${geshtar}`);
    emit(`!SS_DUNES = ${dunes}`);emit(`!SS_LEFT_DUNES = ${leftDunes}`);emit(`!SS_BREAK_LIMIT = ${breakLimit}`);
    emit(`!SS_ENDING = $${endingHex}`);emit(`!SS_ARENA = 340`);
    emit(`!SS_ESCAPE_DOOR = ${hex4(escapeDoor)}`);
    emit(`!SS_DOOR_FIRST = ${hex4(ss.shipDoors[0])}`);emit(`!SS_DOORS = ${ss.shipDoors.length}`);
    emit(`!SS_FLIGHT_DOOR = ${hex4(ss.flightDoor)}`);emit(`!SS_CRASH_EVENT = ${hex4(ss.crashEvents.crash)}`);
    for(const [k,v] of Object.entries(ss.breakout))emit(`!SS_EV_${k.toUpperCase()} = ${hex4(v)}`);
    emit(`!SS_SHIP_SONG = ${hex2(sw.shipSong)}`);
    emit(`!SS_ALARM_SONG = ${hex4(sw.alarmSong[0]|sw.alarmSong[1]<<8)}`);
    emit(`!SS_ALARM_PARAMS = ${hex4(sw.alarmSong[2]|sw.alarmSong[3]<<8)}`);
    emit(`!SS_MONSTER_A = ${monsters[0]}`);emit(`!SS_MONSTER_B = ${monsters[1]}`);
    // Map tables: ship maps, hold maps, fled species, monsters per room.
    bytes('ss_fled',[...fled,0]);
    words('ss_ship_maps',[...sw.shipMaps,0xffff]);
    words('ss_hold_maps',[...ss.holdMaps,0xffff]);
    words('ss_squares',Array.from({length:128},(_,i)=>i*i));
    // Per ship map: monster count, then the browser's floor-spot orders for
    // the monster grid (16 px) and the fire sites (24 px), each sorted by
    // hash(map*977+x, y) over the whole map (stable for ties, like
    // Array.sort), stored as cell indices (x, y bytes).
    const firstPiece=map=>{const list=pieces(map);return list.length?[list[0].w,list[0].h]:[0,0];};
    const orders=[];
    for(const map of sw.shipMaps){
      const [W,H]=firstPiece(map);assert(W>0&&H>0&&W<=128&&H<=128,'ship map size '+map);
      const order=(step)=>{const out=[];const w=W*16,h=H*16;
        for(let y=step/2;y<h;y+=step)for(let x=step/2;x<w;x+=step)out.push({x,y,i:(x-step/2)/step,j:(y-step/2)/step,o:hash(map*977+x,y)});
        return out.map((s,k)=>({...s,k})).sort((a,b)=>a.o-b.o||a.k-b.k);};
      // Only the head of each order is kept: the runtime takes the first
      // landable, spread-out spots, a few out of the first hundreds.
      const keep=256,monsterSpots=(counts[map]??0)?order(16).slice(0,keep):[],siteSpots=order(24).slice(0,keep);
      orders.push({map,W,H,count:counts[map]??0,monsterSpots,siteSpots});
    }
    // Directory: map.w, count.w, monster spots ptr.w + n.w, site spots ptr.w + n.w
    emit('ss_ship_dir:');
    for(const o of orders)emit(`\tdw ${o.map},${o.count},ss_spots_m_${o.map},${o.monsterSpots.length},ss_spots_s_${o.map},${o.siteSpots.length}`);
    emit('\tdw $FFFF');
    for(const o of orders){
      emit(`ss_spots_m_${o.map}:`);for(let k=0;k<o.monsterSpots.length;k+=16)emit('\tdb '+o.monsterSpots.slice(k,k+16).flatMap(s=>[hex2(s.i),hex2(s.j)]).join(','));
      emit(`ss_spots_s_${o.map}:`);for(let k=0;k<o.siteSpots.length;k+=16)emit('\tdb '+o.siteSpots.slice(k,k+16).flatMap(s=>[hex2(s.i),hex2(s.j)]).join(','));
    }
    emit(`; sandship: ${sw.shipMaps.length} ship maps, monsters ${monsters.join('/')} (counts ${JSON.stringify(counts)}), fled ${fled.join('/')}`);

    // --- The wreck's look (sandship-wreck.js getColor / renderLine) -------
    // Palette transforms: a colour word is split into its low byte (red, green
    // bits 0-2) and high byte (green bits 3-4, blue), each looked up in a
    // 16-bit table; the two halves add up to the transformed colour.
    // White-out (renderLine: out + (255 - out) * white): SS_WHITE_LEVELS + 1
    // levels f = L / SS_WHITE_LEVELS.
    const WL=12;
    const clamp=(v,lo,hi)=>Math.max(lo,Math.min(hi,v));
    const whiteLo=[],whiteHi=[];
    for(let L=0;L<=WL;L++){
      const f=L/WL,W=v=>Math.round(v+(31-v)*f);
      for(let lo=0;lo<256;lo++){const r=lo&31,gl=lo>>5;whiteLo.push(W(r)|Math.floor(gl*(1-f))<<5);}
      for(let hi=0;hi<128;hi++){const b=hi>>2,gh=hi&3;whiteHi.push(W(b)<<10|Math.round(8*gh*(1-f)+31*f)<<5);}
    }
    // Every transformed colour of every level stays a valid 15-bit colour
    // within one unit of the exact per-channel blend.
    for(let L=0;L<=WL;L++)for(let c=0;c<0x8000;c+=7){
      const v=whiteLo[L*256+(c&255)]+whiteHi[L*128+(c>>8)],f=L/WL;
      assert(v<0x8000,'white table overflow');
      const g=c>>5&31,want=Math.round(g+(31-g)*f);assert(Math.abs((v>>5&31)-want)<=1,'white table green');
    }
    // Firelight and the red alarm (getColor, BG1/BG2 pixels): red + dr,
    // green + dg, blue + db, dr 2..7, dg -2..0, db -4..-2 (integer parts of
    // the browser's per-frame offsets). Lo tables by dr, hi tables by (dg, db).
    const tintLo=[],tintHi=[];
    for(let dr=2;dr<=7;dr++)for(let lo=0;lo<256;lo++){const r=lo&31,gl=lo>>5;tintLo.push(Math.min(31,r+dr)|gl<<5);}
    for(let dg=-2;dg<=0;dg++)for(let db=-4;db<=-2;db++)for(let hi=0;hi<128;hi++){const b=hi>>2,gh=hi&3;tintHi.push(Math.max(0,b+db)<<10|clamp(8*gh+dg,0,24)<<5);}
    // The alarm pulse and the firelight flicker, from the browser's formulas:
    // alarm = phase<24 ? sin(phase*pi/24)*4 : 0 over a 120-frame cycle, flicker
    // = hash(age>>2, block)*2 (one block for the whole screen: the centre one).
    const alarmSrc=grab(swText,/const phase=age%120,alarm=phase<24\?Math\.sin\(phase\*Math\.PI\/24\)\*4:0,flicker=hash\(age>>2,\(x>>5\)\+\(y>>5\)\*8\)\*2/,'alarm formula')[0];
    assert(alarmSrc,'alarm');
    const block=(128>>5)+(112>>5)*8;
    const alarmA=[],alarmB=[],alarmC=[];
    for(let ph=0;ph<120;ph++){const a=ph<24?Math.sin(ph*Math.PI/24)*4:0;alarmA.push(Math.round(a*256));alarmB.push(Math.round(a*0.4*256));alarmC.push(Math.round(a*0.5*256));}
    const flickA=[],flickB=[];
    for(let k=0;k<256;k++){const f=hash(k,block)*2;flickA.push(Math.min(511,Math.round(f*256)));flickB.push(Math.round(f*0.5*256));}
    // Breach outline (breachDepth >= 0) per scanline, for 4 x 4 quantised
    // phases of its jagged edge (sin(5a + bx), sin(11a + by)): left and right
    // offsets from the centre for dy = -SS_BREACH_H..SS_BREACH_H, $80 = none.
    const [,radiusSrc]=grab(swText,/export function findBreach\(canLand,\{x,y,dx,dy\},radius=(\d+)\)/,'breach radius');
    const radius=Number(radiusSrc);
    grab(swText,/const reach=\(b,a\)=>b\.radius\*\(1\+\.18\*Math\.sin\(a\*5\+b\.x\)\+\.1\*Math\.sin\(a\*11\+b\.y\)\+\.06\*Math\.sin\(a\*23\)\);/,'breach reach');
    grab(swText,/const dx=x-b\.x,dy=\(y-b\.y\)\*1\.25,d=Math\.hypot\(dx,dy\);/,'breach depth');
    const reach=(b,a)=>b.radius*(1+.18*Math.sin(a*5+b.x)+.1*Math.sin(a*11+b.y)+.06*Math.sin(a*23));
    const depth=(b,dx,dy)=>{const yy=dy*1.25;return reach(b,Math.atan2(yy,dx))-Math.hypot(dx,yy);};
    const BH=Math.ceil(radius*1.34/1.25)+1;
    const spans=[],rims=[];
    for(let py=0;py<4;py++)for(let px=0;px<4;px++){
      const b={radius,x:(px+.5)*Math.PI/2,y:(py+.5)*Math.PI/2};
      for(let dy=-BH;dy<=BH;dy++){
        let l=null,r=null;
        for(let dx=-80;dx<=80;dx++)if(depth(b,dx,dy)>=0){if(l===null)l=dx;r=dx;}
        assert(l===null||l>=-127&&r<=127,'breach span');
        spans.push(l===null?0x80:l&255,l===null?0x80:r&255);
      }
      // The five rim fires (prepareSites): angle i*2pi/5 + .4, 4 px up.
      for(let i=0;i<5;i++){const a=i*Math.PI*2/5+.4,rr=reach(b,a);rims.push(Math.round(Math.cos(a)*rr)&255,Math.round(Math.sin(a)*rr/1.25-4)&255);}
    }
    grab(swText,/list\.push\(\{x:b\.x\+Math\.cos\(a\)\*rr,y:b\.y\+Math\.sin\(a\)\*rr\/1\.25-4,seed:40\+i\*5,rim:true\}\);/,'rim sites');
    // The desert under the hull (sand()): its colour down a column, as a
    // 128-line pattern scrolled by 1.5 px per frame.
    grab(swText,/s>1\?rgb\(31,25,17\):s>\.2\?rgb\(29,21,13\):s>-\.8\?rgb\(26,18,11\):rgb\(21,13,8\)/,'sand colours');
    const rgb=(r,g,b)=>clamp(r|0,0,31)|clamp(g|0,0,31)<<5|clamp(b|0,0,31)<<10;
    const sand=[];
    for(let k=0;k<128;k++){
      const wy=k*0.546875,u=0,s=Math.sin(u*.16+Math.sin(wy*.09)*2.4)+Math.sin(u*.05-wy*.07)*.6;
      sand.push(s>1?rgb(31,25,17):s>.2?rgb(29,21,13):s>-.8?rgb(26,18,11):rgb(21,13,8));
    }
    emit(`!SS_WHITE_LEVELS = ${WL}`);
    emit(`!SS_BREACH_H = ${BH}`);
    emit(`!SS_BREACH_LINES = ${2*BH+1}`);
    words('ss_tint_lo',tintLo);
    words('ss_tint_hi',tintHi);
    words('ss_alarm_a',alarmA);words('ss_alarm_b',alarmB);words('ss_alarm_c',alarmC);
    words('ss_flick_a',flickA);words('ss_flick_b',flickB);
    bytes('ss_breach_spans',spans);
    bytes('ss_breach_rims',rims);
    words('ss_sand',sand);
    // The white tables go to the code bank's spare half (they are large).
    whiteTables={whiteLo,whiteHi};
    emit(`; wreck look: ${WL+1} white levels, tint 6 x 9 tables, breach ${2*BH+1} lines x 16 phases`);
  }

  writeFileSync(join(outDir,'tables.asm'),out.join('\n')+'\n');
  // The Sandship white-out tables (13 levels x 768 bytes), placed by
  // module.asm in the code bank's spare space.
  {
    const w=[];const h4=v=>'$'+(v&0xffff).toString(16).toUpperCase().padStart(4,'0');
    w.push('; Generated by snes/gen/destroy.mjs (Sandship white-out). Do not edit.');
    w.push('ss_white_lo:');for(let i=0;i<whiteTables.whiteLo.length;i+=8)w.push('\tdw '+whiteTables.whiteLo.slice(i,i+8).map(h4).join(','));
    w.push('ss_white_hi:');for(let i=0;i<whiteTables.whiteHi.length;i+=8)w.push('\tdw '+whiteTables.whiteHi.slice(i,i+8).map(h4).join(','));
    writeFileSync(join(outDir,'white.asm'),w.join('\n')+'\n');
  }
  writeFileSync(join(outDir,'reactions.json'),JSON.stringify(reactions,null,1));
}
