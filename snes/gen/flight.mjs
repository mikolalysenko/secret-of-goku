// Data generator for the flight module (snes/src/modules/flight).
// Every table comes from the browser engine's own JavaScript or from the
// cartridge: exported constants are imported, and the constants that
// engine/native-local-flight.js and engine/dungeon-geometry.js keep private
// are evaluated from their own source text, so the cartridge and the browser
// share one definition. Output: dist/snes/gen/flight/tables.asm.
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';

const hex2=v=>'$'+(v&255).toString(16).toUpperCase().padStart(2,'0');
const hex4=v=>'$'+(v&0xffff).toString(16).toUpperCase().padStart(4,'0');
const fail=m=>{throw Error('flight generator: '+m);};
const assert=(c,m)=>{if(!c)fail(m);};

// Sealed black regions of the cave tileset are found at run time by a
// bounded flood fill (terrain.asm fl_rockcap). These limits must cover every
// sealed region of every native layout; the generator proves it below.
export const ROCKCAP_MAX_CELLS=64;
export const ROCKCAP_WINDOW=16;       // bounding box limit in each axis

export async function generate({rom,repo,outDir}){
  const engine=name=>import(pathToFileURL(join(repo,'engine',name)).href);
  const terrain=await engine('flight-terrain.js');
  const geometry=await engine('dungeon-geometry.js');
  const {palaceBraziers}=await engine('palace-braziers.js');
  const {ceilingExits}=await engine('ceiling-exits.js');
  const romTools=await import(pathToFileURL(join(repo,'tools/rom/rom.mjs')).href);
  const word=a=>rom[a]|rom[a+1]<<8;

  // ---------------------------------------------------------------------
  // Private constants of native-local-flight.js, evaluated from its source.
  const flightSrc=readFileSync(join(repo,'engine/native-local-flight.js'),'utf8');
  const top=flightSrc.slice(0,flightSrc.indexOf('export function createNativeLocalFlight'));
  const body=top.split('\n').filter(l=>!/^\s*import\b/.test(l)).join('\n');
  const names=['scenery','forestBanks','earthBanks','streamBanks','caveBanks','palaceGaps','fortressGaps','castleGaps','caveGaps','movementFloor','openingExits'];
  for(const n of names)assert(new RegExp(`const ${n}=`).test(body),`native-local-flight.js no longer defines ${n}`);
  const local=new Function('smallScenery','terrainBanks','blankGroundZero','lilyPads',`${body}\nreturn {${names.join(',')}};`)(terrain.smallScenery,terrain.terrainBanks,terrain.blankGroundZero,terrain.lilyPads);
  for(const code of[0x20,0x2f,0x30,0x3f])assert(local.movementFloor(code),'movement floors changed');
  for(const code of[0,0x10,0x40,0xc1])assert(!local.movementFloor(code),'movement floors changed');
  // Private constants of dungeon-geometry.js.
  const geoSrc=readFileSync(join(repo,'engine/dungeon-geometry.js'),'utf8');
  const privateSet=name=>{
    const m=geoSrc.match(new RegExp(`const ${name}=new Set\\((\\[[^\\]]*\\])\\)`));
    assert(m,`dungeon-geometry.js no longer defines ${name}`);
    return new Set(JSON.parse(m[1]));
  };
  const blankZero=privateSet('blankZero'),wallTilesets=privateSet('wallTilesets'),falsePalaceFloor=privateSet('falsePalaceFloor');
  const {dungeonGroups,dungeonAirTiles,dungeonSpecialScenes,createDungeonGeometry}=geometry;

  // ---------------------------------------------------------------------
  const out=[];
  const emit=s=>out.push(s);
  const bytes=(label,arr,per=16)=>{
    if(label)emit(`${label}:`);
    for(let i=0;i<arr.length;i+=per)emit('\tdb '+Array.from(arr.slice(i,i+per),hex2).join(','));
  };
  const words=(label,arr,per=8)=>{
    if(label)emit(`${label}:`);
    for(let i=0;i<arr.length;i+=per)emit('\tdw '+Array.from(arr.slice(i,i+per),v=>typeof v==='string'?v:hex4(v)).join(','));
  };
  emit('; Generated by snes/gen/flight.mjs from engine/*.js and the cartridge. Do not edit.');
  emit(`!FL_ROCKCAP_MAX = ${ROCKCAP_MAX_CELLS}`);
  emit(`!FL_ROCKCAP_WIN = ${ROCKCAP_WINDOW}`);

  // ---------------------------------------------------------------------
  // Metatile sets (0-383) as 48-byte bitsets; one pointer per tileset and
  // category (0 = empty). Category order is fixed by terrain.asm.
  const bitsets=new Map();let nextSet=0;
  const bitset=(set,label)=>{
    if(!set||!set.size)return 0;
    const bits=new Uint8Array(48);
    for(const v of set){assert(Number.isInteger(v)&&v>=0&&v<384,`set value ${v} out of range (${label})`);bits[v>>3]|=1<<(v&7);}
    const key=Array.from(bits).join(',');
    if(!bitsets.has(key))bitsets.set(key,{name:`fl_set_${nextSet++}`,bits});
    return bitsets.get(key).name;
  };
  const bankTiles=ts=>ts===2?local.forestBanks:ts===0||ts===1?local.streamBanks:ts===10?local.caveBanks:terrain.terrainBanks[ts];
  const categories=[
    ['SCENERY',ts=>local.scenery[ts]],
    ['BANK',ts=>bankTiles(ts)],
    ['LILY',ts=>terrain.lilyPads[ts]],
    ['SMALL',ts=>terrain.smallScenery[ts]],
    ['DAIR',ts=>dungeonAirTiles[ts]],
  ];
  const catTables=categories.map(([name,get])=>({name,ptrs:Array.from({length:64},(_,ts)=>bitset(get(ts),`${name} ${ts}`))}));
  const special={
    fl_set_cavegap:bitset(local.caveGaps,'caveGaps'),
    fl_set_castlegap:bitset(local.castleGaps,'castleGaps'),
    fl_set_fortgap:bitset(local.fortressGaps,'fortressGaps'),
    fl_set_palacegap:bitset(local.palaceGaps,'palaceGaps'),
    fl_set_falsepalace:bitset(falsePalaceFloor,'falsePalaceFloor'),
    fl_set_brazier:bitset(new Set(palaceBraziers.flat()),'palaceBraziers'),
  };
  // Village flowers/shrubs and Tree Palace flowers (paired BG2 artwork of
  // the solid placeholders 187/188 and 185): checked against the source.
  const villageFlowers=[272,273,274,275,276,277,278,288,289,290,291,292,293,294];
  const treeFlowers=[250,251,252];
  assert(flightSrc.includes(`[${villageFlowers.join(',')}].includes(foreground)`),'village flower list changed in native-local-flight.js');
  assert(flightSrc.includes(`[${treeFlowers.join(',')}].includes(foreground)`),'Tree Palace flower list changed in native-local-flight.js');
  special.fl_set_villageflower=bitset(new Set(villageFlowers),'village flowers');
  special.fl_set_treeflower=bitset(new Set(treeFlowers),'tree flowers');
  // Other literals the runtime hard-codes, asserted against the source so a
  // change there fails this build.
  for(const [snippet,what] of [
    ['tileset===1&&t.layer===0&&[171,172].includes(metatile)&&t.code===0xc1&&t.replacement===343-t.tile','carved heads'],
    ['tileset===2&&word(0xdc)!==25?5:16','forest bank span'],
    ['betweenShores(small,8)','small scenery span'],
    ["tileset===9&&t.layer===1&&t.code===0&&metatile===222",'ruins balcony'],
    ['word(0xdc)===139&&t.ty>=59&&t.ty<=65&&t.tx>=12&&t.tx<=21&&(t.tx<16||t.tx>17)','Water Palace pockets'],
    ['tileset===15&&[302,303,304].includes(word(0xdc))||tileset===10&&word(0xdc)>=284&&word(0xdc)<=297','castle/cave gap maps'],
    ['tileset===21&&t.layer===0&&word(0xdc)>=248&&word(0xdc)<=251','Fortress gap maps'],
    ['x>=184&&x<=408&&y>=292&&y<=432','Mana Beast arena'],
    ['word(0xdc)!==32||t.layer!==1||t.tx<24||t.tx>29||t.ty<18||t.ty>43','ferry corridor'],
    ['![98,99].includes(word(0xdc))||t.layer!==0||t.ty!==9||t.tx<24||t.tx>27||t.tile!==122','ship rail'],
    ['for(const dy of[-4,0,4])for(const dx of[-6,0,6])','flight footprint'],
    ['[[0xe200,36,26],[0xe400,56,40]]','companion trail box'],
    ['Math.min(velocity,14-travel[at-0x1e])','per-frame travel limit'],
  ])assert(flightSrc.includes(snippet),`native-local-flight.js changed: ${what}`);
  for(const [snippet,what] of [
    ['span(p,1,0,airMaterial,48,c)||span(p,0,1,airMaterial,48,c)','air route span'],
    ['span(t,1,1,airMaterial,16,c)||span(t,1,-1,airMaterial,16,c)','castle diagonal span'],
    ["[16,19,32,35].includes(metatile(t,c))",'Tree Palace dais'],
    ['for(let n=1;n<=12;n++)','cave void span'],
    ['c.map===72&&c.width===64&&c.height===64&&t.layer===0&&t.tile!==70','Joch room'],
    ['[9,10,15].includes(c.tileset)','air shore stairs'],
    ['c.tileset===9&&metatile(t,c)===319','ruins spikes'],
  ])assert(geoSrc.includes(snippet),`dungeon-geometry.js changed: ${what}`);

  // Tileset flags: bit0 blankGroundZero, bit1 wall tileset, bit2 blank zero
  // (dungeon floors), bit3 stairs/currents count as air shores.
  const tsFlags=Array.from({length:64},(_,ts)=>(terrain.blankGroundZero.has(ts)?1:0)|(wallTilesets.has(ts)?2:0)|(blankZero.has(ts)?4:0)|([9,10,15].includes(ts)?8:0));
  bytes('fl_ts_flags',tsFlags);
  for(const t of catTables)words(`fl_cat_${t.name.toLowerCase()}`,t.ptrs.map(p=>p||'$0000'));
  for(const {name,bits}of bitsets.values())bytes(name,bits);
  // Sets the runtime names directly get their own copy (asar labels cannot
  // alias other labels).
  for(const [label,name]of Object.entries(special)){
    assert(name,`empty special set ${label}`);
    bytes(label,[...bitsets.values()].find(b=>b.name===name).bits);
  }

  // ---------------------------------------------------------------------
  // Per-map flags. Dungeon context comes from dungeon-geometry.js context()
  // itself, probed on a synthetic machine for every map.
  const fake=(ram=new Uint8Array(0x20000))=>({ram,cart:{data:rom},frames:1000,ppu:{mode:1},
    cpu:{r:new Uint8Array(8),br:new Uint16Array(8),cyclesLeft:0,cycle(){}}});
  const headerAt=map=>0x80000+word(0x87000+map*2);
  const tilesetOf=map=>rom[headerAt(map)+2]&63;
  const context=new Uint8Array(512);
  {
    const ram=new Uint8Array(0x20000),g=createDungeonGeometry(fake(ram));
    for(let map=0;map<511;map++){
      ram[0xdc]=map&255;ram[0xdd]=map>>8;ram[0xc0]=0;ram[0xc1]=8;ram[0xc2]=0;ram[0xc3]=8;
      g.invalidate();if(g.context())context[map]=1;
    }
  }
  // Placement extents: inside the interior every dungeon map's placement is
  // the rectangle of its always-visible pieces for any story flags (the same
  // property the destroy generator relies on), so placed() is two compares.
  function pieces(map){
    const start=0x80000+word(0x85000+map*2),end=0x80000+word(0x85002+map*2);
    if(end<=start||end-start>4000)return[];
    const list=[];let layer=0;
    for(let p=start;p<end;){
      const flag=rom[p];if(flag>=254){layer=flag===255?1:0;p++;continue;}
      if(p+4>=end)break;
      const id=rom[p+2]|(rom[p+3]&1)<<8|(rom[p+4]&1)<<9,bank=id<0xa3?0xd:id<0x206?0xe:id<0x300?0xf:0xc;
      const address=(bank<<16)+word(0xd0004+id*2);
      list.push({layer,flag,min:rom[p+1]>>4,max:rom[p+1]&15,x:rom[p+3]>>1,y:rom[p+4]>>1,w:(rom[address]>>1)+1,h:(rom[address+1]>>1)+1});
      p+=5;
    }
    return list;
  }
  const ext=Array.from({length:512},()=>[0,0,0,0]);
  for(let map=0;map<511;map++){
    if(!context[map])continue;
    const list=pieces(map);if(!list.length)continue;
    const W=Math.min(128,list[0].w),H=Math.min(128,list[0].h);
    for(let l=0;l<2;l++){
      const always=list.filter(p=>p.layer===l&&p.min===0&&p.max===15),cond=list.filter(p=>p.layer===l&&!(p.min===0&&p.max===15));
      const x1=always.length?Math.min(128,Math.max(...always.map(p=>p.x+p.w))):0,y1=always.length?Math.min(128,Math.max(...always.map(p=>p.y+p.h))):0;
      for(let y=1;y<H-1;y++)for(let x=1;x<W-1;x++){
        const covered=always.some(p=>y>=p.y&&y<p.y+p.h&&x>=p.x&&x<p.x+p.w);
        assert(covered===(x<x1&&y<y1),`map ${map} layer ${l}: unconditional placement is not a rectangle at ${x},${y}`);
        assert(!cond.some(p=>y>=p.y&&y<p.y+p.h&&x>=p.x&&x<p.x+p.w)||(x<x1&&y<y1),`map ${map} layer ${l}: conditional piece outside the rectangle at ${x},${y}`);
      }
      ext[map][l*2]=x1;ext[map][l*2+1]=y1;
    }
  }
  // Floor holes (supported(): canLand and the walking check): the browser's
  // only providers (lab.js missingFloor) report holes on the Sandship's maps
  // (sandship-wreck.js floorHole needs active(), which needs onShip()) and in
  // Frieza's arena (frieza.js floorHole needs ownsArena(), one map). Flight
  // asks the cartridge's providers on those maps only (!FLM_HOLES).
  const engineSrc=name=>readFileSync(join(repo,'engine',name),'utf8');
  const labSrc=engineSrc('lab.js'),wreckSrc=engineSrc('sandship-wreck.js'),shipSrc=engineSrc('sandship.js'),friezaSrc=engineSrc('frieza.js');
  assert(labSrc.includes('missingFloor:(x,y,l)=>!!(mod.frieza?.floorHole(x,y,l)||mod.sandship?.floorHole(x,y))'),'lab.js missingFloor providers changed');
  assert(shipSrc.includes('floorHole:(x,y)=>wreck.floorHole(x,y)'),'sandship.js floorHole changed');
  assert(wreckSrc.includes('floorHole(x,y){const b=state().wreck?.breach;return !!(b&&active()&&'),'sandship-wreck.js floorHole no longer needs active()');
  assert(/const active=\(\)=>[^\n;]*&&onShip\(\)/.test(wreckSrc)&&wreckSrc.includes('const onShip=()=>shipMaps.includes(word(0xdc));'),'sandship-wreck.js active() no longer needs onShip()');
  const shipMapsM=wreckSrc.match(/export const shipMaps=(\[[\d,]+\]);/);
  assert(shipMapsM,'sandship-wreck.js shipMaps moved');
  assert(friezaSrc.includes('floorHole(x,y,layer){const b=s.boss;return !!(api.ownsArena()&&'),'frieza.js floorHole no longer needs ownsArena()');
  const arenaM=friezaSrc.match(/ownsArena\(\)\{return [^}\n]*&&map\(\)===(\d+);\}/);
  assert(arenaM,'frieza.js ownsArena() no longer names one map');
  const holeMaps=new Set([...JSON.parse(shipMapsM[1]),Number(arenaM[1])]);

  // Map flags, bit per special rule (terrain.asm !FLM_*). Rules that also
  // name a tileset are folded in here.
  const mapFlags=new Uint16Array(512);
  for(let map=0;map<512;map++){
    const ts=map<511?tilesetOf(map):-1;let f=0;
    if(context[map])f|=0x0001;
    if(map===32)f|=0x0002;                                  // Karon's ferry corridor
    if(map===98||map===99)f|=0x0004;                        // Sandship deck rail
    if(local.openingExits[map])f|=0x0008;                   // opening field exits
    if(map===253)f|=0x0010;                                 // Mana Beast arena
    if(map===25)f|=0x0020;                                  // long forest bank span
    if(ts===15&&[302,303,304].includes(map))f|=0x0040;      // castle chasms
    if(ts===10&&map>=284&&map<=297)f|=0x0080;               // Gaia's lava and air
    if(ts===21&&map>=248&&map<=251)f|=0x0100;               // Fortress chasms
    if(map===72)f|=0x0200;                                  // Joch's training room
    if(map===139)f|=0x0400;                                 // Water Palace stair pockets
    if(holeMaps.has(map))f|=0x0800;                         // floor holes possible
    mapFlags[map]=f;
  }
  words('fl_map_flags',Array.from(mapFlags));
  bytes('fl_map_ext',ext.flat());

  // ---------------------------------------------------------------------
  // Recovery search order (settle()): candidates of a +-128 px grid in 8 px
  // steps, pushed dy-major, then sorted by squared distance (stable).
  assert(flightSrc.includes('for(let dy=-128;dy<=128;dy+=8)for(let dx=-128;dx<=128;dx+=8)'),'recovery grid changed');
  const cand=[];
  for(let dy=-16;dy<=16;dy++)for(let dx=-16;dx<=16;dx++)cand.push({dx,dy,d:dx*dx+dy*dy,i:cand.length});
  cand.sort((a,b)=>a.d-b.d||a.i-b.i);
  bytes('fl_recover_order',cand.flatMap(c=>[c.dx&255,c.dy&255]));

  // ---------------------------------------------------------------------
  // Opening field exits (flightExit): map, tile x, y, n, axis (0 = x, 1 = y),
  // direction sign, door. $FFFF ends the list.
  const exitRows=[];
  for(const [map,list]of Object.entries(local.openingExits))for(const e of list){
    const axis=e.dx?0:1,sign=(e.dx??e.dy)>0?1:0xff;
    exitRows.push(`\tdw ${hex4(Number(map))}\n\tdb ${[e.x,e.y,e.n,axis,sign].map(hex2).join(',')}\n\tdw ${hex4(0x800+e.door)}`);
  }
  emit('fl_opening_exits:');emit(exitRows.join('\n'));emit('\tdw $FFFF');

  // ---------------------------------------------------------------------
  // Ceiling exits: room -> route; route -> exterior map and original door.
  const route=new Uint8Array(512);
  ceilingExits.forEach((r,i)=>{for(const room of r.rooms){assert(!route[room],`room ${room} has two roof routes`);route[room]=i+1;}});
  bytes('fl_roof_route',route);
  words('fl_roof_exit',ceilingExits.flatMap(r=>[r.map,r.door]));
  emit(`!FL_ROOF_ROUTES = ${ceilingExits.length}`);
  emit(`!FL_ROOF_ROOMS = ${route.filter(Boolean).length}`);

  // ---------------------------------------------------------------------
  // Cave rock caps: prove the run-time flood fill limits for every native
  // layout (all piece variants) of every cave-tileset dungeon map.
  let checked=0,maxCells=0,maxBox=0;
  for(let map=0;map<511;map++){
    if(!context[map]||tilesetOf(map)!==10)continue;
    const list=pieces(map),W=Math.min(128,list[0].w),H=Math.min(128,list[0].h);
    const condFlags=[...new Set(list.filter(p=>!(p.min===0&&p.max===15)).map(p=>p.flag))];
    const values=condFlags.map(f=>[...new Set(list.filter(p=>p.flag===f).flatMap(p=>[p.min,Math.min(15,p.max+1),0,15]))]);
    const combos=values.reduce((acc,vs)=>acc.flatMap(c=>vs.map(v=>[...c,v])),[[]]);
    const seenLayouts=new Set();
    for(const combo of combos){
      const flags={};condFlags.forEach((f,i)=>flags[f]=combo[i]);
      const m=romTools.readMap(rom,map,'m',flags),hdr=rom[headerAt(map)+2],base=(hdr&64)?192:0;
      const raw=new Int16Array(128*128).fill(-1);
      for(let y=0;y<Math.min(H,m.composite.height);y++)for(let x=0;x<Math.min(W,m.composite.width);x++){
        const v=m.composite.layers.background[y*m.composite.width+x];if(v!==null)raw[y*128+x]=v-base;
      }
      const key=Array.from(raw).join(',');if(seenLayouts.has(key))continue;seenLayouts.add(key);
      const placed=(x,y)=>x<ext[map][0]&&y<ext[map][1];
      const seen=new Uint8Array(128*128);
      for(let y=0;y<H;y++)for(let x=0;x<W;x++){
        const k=y*128+x;if(seen[k]||raw[k]!==5)continue;
        const cells=[k];seen[k]=1;let open=false;
        for(let i=0;i<cells.length;i++){
          const cx=cells[i]%128,cy=cells[i]>>7;if(!placed(cx,cy))open=true;
          for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){
            if(!dx&&!dy)continue;const nx=cx+dx,ny=cy+dy,nk=ny*128+nx;
            if(nx<0||ny<0||nx>=W||ny>=H){open=true;continue;}
            if(raw[nk]===0)open=true;
            if(raw[nk]===5&&!seen[nk]){seen[nk]=1;cells.push(nk);}
          }
        }
        if(!open){
          const xs=cells.map(c=>c%128),ys=cells.map(c=>c>>7),box=Math.max(Math.max(...xs)-Math.min(...xs),Math.max(...ys)-Math.min(...ys))+1;
          maxCells=Math.max(maxCells,cells.length);maxBox=Math.max(maxBox,box);
          assert(cells.length<=ROCKCAP_MAX_CELLS,`map ${map}: sealed cave region of ${cells.length} cells exceeds the flood fill limit`);
          assert(box<=ROCKCAP_WINDOW,`map ${map}: sealed cave region spans ${box} tiles`);
        }
      }
      checked++;
    }
  }
  emit(`; cave layouts checked: ${checked}, largest sealed region ${maxCells} cells, ${maxBox} tiles across`);

  writeFileSync(join(outDir,'tables.asm'),out.join('\n')+'\n');
}
