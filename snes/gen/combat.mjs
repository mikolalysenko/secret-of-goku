// Combat module generator: exact tables for the browser's floating-point
// combat formulas (engine/mana-mod.js), hand sockets from
// engine/goku-animation-data.js, item-name patches (engine/native-equipment.js,
// engine/native-senzu.js) and the placeholder effect cells.
// Output: dist/snes/gen/combat/data.asm (+ defines.asm).
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import vm from 'node:vm';
import {patchItemIcons} from './combat-icons.mjs';
import {FEEL} from './snes-feel.mjs';

const hex=(v,n=2)=>'$'+(v>>>0).toString(16).toUpperCase().padStart(n,'0');
const s8=v=>{if(v<-128||v>127)throw Error(`combat gen: ${v} does not fit a signed byte`);return v&255;};
const dw=list=>list.map(v=>hex(v&0xffff,4)).join(',');
const db=list=>list.map(v=>hex(v&0xff)).join(',');

// Same arithmetic as ManaMod (JavaScript doubles) so the cartridge reproduces
// every rounding of the browser: damageScale(), beam strength, launch arcs.
export const POWER={base:4095,ssj:8191};
export const GI=.9;
export function damageScale(ssj,gi){return Math.round((ssj?POWER.ssj:POWER.base)*(gi?GI:1));}
export function beamProfile(ssj,charge){
  const cap=ssj?45:90,strength=Math.min(1,charge/cap),mega=ssj&&strength>=1;
  return{strength,mega,width:mega?80:5+strength*14,range:mega?640:320,max:mega?64:24,speed:mega?48:32};
}
// Launch arc of updateKnockbacks(): t = age/12 (age 1..12).
export function launchEase(age){const t=Math.min(1,age/12);return 1-(1-t)**2;}

// ManaMod's tuning statics (hit stop, push-back), read from the browser's
// own engine/mana-mod.js: the class is defined, never constructed.
export function manaModStatics(repo){
  const ctx={window:{}};
  vm.runInNewContext(readFileSync(resolve(repo,'engine/mana-mod.js'),'utf8'),ctx);
  const {HIT_STOP,SLIDE,SLIDE_FRAMES}=ctx.window.ManaMod;
  return {HIT_STOP:HIT_STOP.map(r=>[...r]),SLIDE:[...SLIDE],SLIDE_FRAMES};
}

async function animationData(repo){
  const ctx={window:{}};
  vm.runInNewContext(readFileSync(resolve(repo,'engine/goku-animation-data.js'),'utf8'),ctx);
  return ctx.window.GokuAnimationData;
}

// Placeholder effect cells (16x16, 4bpp, OBJ palette 0 colour indices).
// Only used until the fx module provides the real Lucent Beam / Thunderbolt
// cells. Index 1 = light blue (7FB5), 6 = near white (7FBB), 5 = gold (337F),
// 2 = orange (121F) in the field's OBJ palette 0.
function cell(rows){
  const pix=rows.map(r=>r.padEnd(16,'.').split('').map(c=>c==='.'?0:parseInt(c,16)));
  while(pix.length<16)pix.push(Array(16).fill(0));
  const out=[];
  for(const [tx,ty] of [[0,0],[8,0],[0,8],[8,8]]){
    const t=new Uint8Array(32);
    for(let y=0;y<8;y++)for(let x=0;x<8;x++){
      const c=pix[ty+y][tx+x];
      for(let p=0;p<4;p++)if(c>>p&1){const base=(p>>1)*16+y*2+(p&1);t[base]|=0x80>>x;}
    }
    out.push(t);
  }
  return out; // tiles: top-left, top-right, bottom-left, bottom-right
}
