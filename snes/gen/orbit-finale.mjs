// Orbit finale data: the beam struggle's clock (engine/frieza-finale.js
// tickClash / tapClash / clashCamera / descentPose) and the victory beat
// (frieza.js won stage, boss-victory.js), as tables the cartridge reads.
//
// Single source of truth: timings come from the browser's exported
// clashTiming, clashSurges, victoryTiming and bossVictoryTiming. The
// struggle's pressure is a double in the browser; the cartridge keeps it
// in Q31 fixed point (1.0 = 2^31), so every constant here is the browser's
// literal rounded once, and the per-frame decay (.0012 + .0014 * min(1,
// age / 720)) is tabulated per age from the browser's own expression. The
// eases (t^2 (3 - 2t)) are tabulated per frame as 32-bit fractions, so
// Math.round(a + (b - a) * t) can be reproduced exactly for the integer
// mixes the browser's state depends on.
//
// Outputs (dist/snes/gen/orbit-finale/finale.asm): defines (!FNT_*,
// !FNQ_*), the decay table and the ease tables; module.asm includes it in
// its !DATA_ORBIT block.
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {lineTables,FIGHT_R0} from './orbit.mjs';

const Q31=2**31;
const q31=v=>Math.round(v*Q31);
const hexd=v=>'$'+(v>>>0).toString(16).padStart(8,'0');

// The bands above the globe (fdraw.asm bands): the clash's rays all start
// from Goku at (28, 136) (heading 15) or Frieza at (204, 48) (heading 7).
export const BANDS=[{name:'blue',x:28,y:136,vx:229,vy:-114,pal:7},{name:'purple',x:204,y:48,vx:-229,vy:114,pal:1}];
export const BAND_LINES=106,BAND_RS=24;    // rows 0-105; radii 2, 4, ... 48
const BAND_PROF=58;                        // map profile entries (tile x + 2 * tile y)

export async function generate({repo,outDir,xdata}){
  const eng=f=>import(pathToFileURL(join(repo,'engine',f)).href);
  const {clashTiming,clashSurges,victoryTiming,ease,descentPose,clashCamera}=await eng('frieza-finale.js');
  const {orbitHeading}=await eng('orbit-pixels.js');
  const {bossVictoryTiming}=await eng('boss-victory.js');
  const lines=['; Generated by snes/gen/orbit-finale.mjs (do not edit)'];
  const def=(k,v)=>lines.push(`!${k} = ${v}`);
  for(const[k,v]of Object.entries(clashTiming))def(`FNT_${k.toUpperCase()}`,v);
  for(const[k,v]of Object.entries(victoryTiming))def(`FNT_V_${k.toUpperCase()}`,v);
  for(const[k,v]of Object.entries(bossVictoryTiming))if(typeof v==='number')def(`FNT_B_${k.toUpperCase()}`,v);
  clashSurges.forEach((s,i)=>{def(`FNT_SURGE${i}`,s.at);});
  if(clashSurges.length!==3)throw Error('orbit-finale: three surges expected');
  // tickClash / tapClash literals (Q31). The browser's products are taken
  // as the doubles it computes (.036 * .65).
  const Q={P0:.43,CAP:.92,ONE:1,WIN:.975,FAIL:.04,DOWN:.006,UP:.004,TAP:.036,TAPS:.036*.65};
  for(const[k,v]of Object.entries(Q))def(`FNQ_${k}`,q31(v));
  lines.push('; surge losses (Q31 dwords)','orbit_fn_loss:','\tdd '+clashSurges.map(s=>q31(s.loss)).join(', '));
  lines.push('; surge start ages (words)','orbit_fn_surge_at:','\tdw '+clashSurges.map(s=>s.at).join(', '));
  // Per-frame decay, ages 0..720 (later ages use the last entry).
  const decay=[];for(let a=0;a<=720;a++)decay.push(q31(.0012+.0014*Math.min(1,a/720)));
  lines.push('; struggle decay per age (Q31 dwords, 721)','orbit_fn_decay:');
  for(let i=0;i<decay.length;i+=8)lines.push('\tdd '+decay.slice(i,i+8).map(hexd).join(','));
  // Eases as 32-bit fractions; exactly 1 is $FFFFFFFF (mix returns b).
  const frac=t=>t>=1?0xffffffff:Math.min(0xfffffffe,Math.round(t*2**32));
  const table=(name,n,note)=>{
    const v=[];for(let a=0;a<=n;a++)v.push(frac(ease(a/n)));
    lines.push(`; ${note}: ease(age / ${n}), ages 0..${n} (dwords)`,`${name}:`);
    for(let i=0;i<v.length;i+=8)lines.push('\tdd '+v.slice(i,i+8).map(hexd).join(','));
  };
  table('orbit_fn_e110',110,'gather positions');
  table('orbit_fn_e150',clashTiming.gather,'gather camera');
  table('orbit_fn_e240',victoryTiming.return-victoryTiming.descent,'descent camera');
  // The finale view's rays and poses (frieza-finale-view.js) depend only on
  // the phase age once the gather has put Goku at (28, 136) and Frieza at
  // (204, 48): what fx.beam draws for each (rounded ends, the quantised
  // heading, reach = min(360, length), band radius max(2, round(width / 2)
  // * 2); no band below width 1), per age.
  const H={x:28,y:136},B={x:204,y:48},DX=B.x-H.x,DY=B.y-H.y,N=Math.hypot(DX,DY);
  const point=t=>({x:H.x+DX*t,y:H.y+DY*t});
  const ray=(x,y,xx,yy,width)=>{
    if(width<1)return{R:0,length:0,heading:0};
    x=Math.round(x);y=Math.round(y);xx=Math.round(xx);yy=Math.round(yy);
    const length=Math.round(Math.hypot(xx-x,yy-y));
    return{R:Math.max(2,Math.round(width/2)*2),length:Math.min(360,length),heading:orbitHeading(xx-x,yy-y)};
  };
  const words=(name,note,v)=>{lines.push(`; ${note}`,`${name}:`);for(let i=0;i<v.length;i+=12)lines.push('\tdw '+v.slice(i,i+12).join(','));};
  {
    const v=[];
    for(let a=0;a<=clashTiming.launch;a++){const t=ease(a/clashTiming.contact),f=point(.43*t),e=point(1-.57*t),b=ray(H.x,H.y,f.x,f.y,27),p=ray(B.x,B.y,e.x,e.y,30);v.push(b.length,b.heading,p.length,p.heading);}
    words('orbit_fn_launch','launch: blue length, heading, purple length, heading per age (bands 28 and 30)',v);
  }
  {
    const v=[];
    for(let a=0;a<32;a++){const p=point(Math.max(0,.12-a/100)),r=ray(B.x,B.y,p.x,p.y,34*(1-a/40));v.push(r.R,r.length,r.heading);}
    words('orbit_fn_recoil','recoil: purple band radius, length, heading per age 0-31',v);
    const g=[];for(let a=0;a<=clashTiming.recoil;a++)g.push(Math.round(6*Math.sin(Math.PI*Math.min(1,a/clashTiming.recoil))));
    words('orbit_fn_recoil_dx','recoil: Goku pushed back (pixels) per age',g);
  }
  {
    const v=[];
    for(let a=0;a<victoryTiming.beamEnd;a++){
      const grow=ease(a/65),tail=1-ease((a-victoryTiming.beamFade)/(victoryTiming.beamEnd-victoryTiming.beamFade));
      const length=N+grow*260,width=(30+grow*15)*tail,r=ray(H.x,H.y,H.x+DX/N*length,H.y+DY/N*length,width);v.push(r.R,r.length,r.heading);
    }
    words('orbit_fn_win','victory beam: band radius, length, heading per age',v);
  }
  {
    const v=[];
    for(let age=victoryTiming.descent;age<victoryTiming.return;age++){
      const o={hero:{...H},camera:{x:0,y:0,r:0},clash:{phase:'win',age,from:{camera:{x:0,y:0,r:0}}}};
      const p=descentPose(o,age),size=Math.max(16,Math.round(p.size/8)*8);
      v.push(Math.round(p.x)-size/2,Math.round(p.y)-size/2,size);
    }
    words('orbit_fn_descent','descent: Goku\'s top left x, y and size per age from the descent',v);
  }
  // The struggle's ray lengths from where the beams meet: for |dx| = 0-176
  // and |dy| - floor(|dx| / 2) = -2..2, Math.round(Math.hypot(dx, dy))
  // (both rays run at a 1:2 slope; checked over every shown value).
  {
    const L=[];for(let d=0;d<=176;d++)for(let e=-2;e<=2;e++){const dy=(d>>1)+e;L.push(Math.round(Math.hypot(d,dy)));}
    for(let i=0;i<=20000;i++){
      const t=i/20000,p={x:Math.round(28+176*t),y:Math.round(136-88*t)};
      for(const o of[H,B]){const dx=Math.abs(p.x-o.x),dy=Math.abs(p.y-o.y),e=dy-(dx>>1);
        if(e<-2||e>2)throw Error(`orbit-finale: meeting point off the table (${dx}, ${dy})`);
        if(dx>=8&&orbitHeading(p.x-o.x,p.y-o.y)!==(o===H?15:7))throw Error('orbit-finale: struggle heading');}
    }
    lines.push('; struggle ray lengths: |dx| 0-176 x (|dy| - |dx| / 2) -2..2 (bytes)','orbit_fn_hyp:');
    for(let i=0;i<L.length;i+=20)lines.push('\tdb '+L.slice(i,i+20).join(','));
  }
  {
    const v=[];
    for(let a=victoryTiming.reward;a<victoryTiming.acquire;a++){const p=point(1-ease((a-victoryTiming.reward)/(victoryTiming.acquire-victoryTiming.reward)));v.push(Math.round(p.x),Math.round(p.y));}
    words('orbit_fn_pouch','pouch: centre x, y per age from the reward',v);
  }
  // Beam bands above the globe (bands.asm). Per band and radius, the BG map
  // profile of the band's cross-section along d = x + 2y: clear, outer
  // quarter, inner half, outer quarter, clear (thresholds To1 < T1 < T2 <
  // To2 fitted to orbit-effects.js's own pixels, |v| <= R; the true edges
  // have slope -114/229, half a pixel off -1/2 across the screen), as
  // entries of the band tiles (orbit-fx.mjs band.bin: 0 clear, 1 outer,
  // 2 inner, 3 + c - 1 clear|outer at c, 24 + c - 1 outer|inner at c; turned
  // half round they read outer|clear and inner|outer at 22 - c). The
  // windows only cut the band's two ends (u = 0 at the origin, u = reach):
  // per row, the origin's cut and, per reach, the far end's (exact).
  {
    const tilePx=(id,flip,d)=>{if(flip)d=21-d;if(id===0)return 0;if(id===1)return 1;if(id===2)return 2;
      if(id<24){const c=id-2;return d<c?0:1;}const c=id-23;return d<c?1:2;};
    const cands=[[0,0],[1,0],[2,0]];for(let id=3;id<45;id++)cands.push([id,0],[id,1]);
    const prof=[],thr=[];
    for(const b of BANDS){
      for(let k=0;k<BAND_RS;k++){
        // classes per d: 0 clear (low d), 1 outer (low), 2 inner, 3 outer (high), 4 clear (high)
        const R=2+k*2,h=[0,1,2,3,4].map(()=>new Int32Array(560));
        for(let y=0;y<BAND_LINES;y++)for(let x=0;x<256;x++){
          const ox=x-b.x,oy=y-b.y,v=(-ox*b.vy+oy*b.vx)>>8,d=x+2*y;
          // v grows with d for Goku's band, falls with it for Frieza's
          const w=b.vx>0?v:-v;
          let c;
          if(w<-R)c=0;else if(w>R)c=4;
          else{const idx=Math.min(3,Math.floor((v+R)*4/(2*R+1)));c=idx===1||idx===2?2:(b.vx>0?(idx===0?1:3):(idx===3?1:3));}
          h[c][d]++;
        }
        // each threshold fitted on its own pair of classes: e(T) = #lo at d >= T + #hi at d < T
        const fit=(lo,hi)=>{let e=0;for(let d=0;d<560;d++)e+=h[lo][d];let best=e,T=0;
          for(let d=0;d<560;d++){e+=h[hi][d]-h[lo][d];if(e<best){best=e;T=d+1;}}return T;};
        const To1=fit(0,1),T1=fit(1,2),T2=fit(2,3),To2=fit(3,4);
        if(!(To1<=T1&&T1<=T2&&T2<=To2))throw Error(`orbit-finale: band thresholds out of order ${b.name} R ${R}`);
        const col=d=>d<To1?0:d<T1?1:d<T2?2:d<To2?1:0;
        for(let i=0;i<BAND_PROF;i++){
          let best=Infinity,pick=null;
          for(const[id,flip]of cands){
            let e=0;for(let py=0;py<8;py++)for(let px=0;px<8;px++){const d=px+2*py;if(tilePx(id,flip,d)!==col(8*i+d))e++;}
            if(e<best){best=e;pick=[id,flip];}
          }
          prof.push(pick[0]|(b.pal<<10)|(pick[1]?0xc000:0));
        }
        thr.push(To1,T1,T2,To2);
        lines.push(`; band ${b.name} R ${R}: To1 ${To1} T1 ${T1} T2 ${T2} To2 ${To2}`);
      }
    }
    // the ends: per row, the origin's cut (Goku's left bound, Frieza's right)
    // and per reach the far end's (Goku's right bound, Frieza's left)
    const clamp=v=>v<0?0:v>255?255:v;
    const fdiv=(n,d)=>Math.floor(n/d),cdiv=(n,d)=>Math.ceil(n/d);
    const origin=[],far=[[],[]];
    for(let y=0;y<BAND_LINES;y++)origin.push(clamp(28+cdiv(114*(y-136),229)));
    for(let y=0;y<BAND_LINES;y++)origin.push(clamp(204+fdiv(114*(y-48),229)));
    for(let L=0;L<=360;L++)for(let y=0;y<BAND_LINES;y++)far[0].push(clamp(28+fdiv(256*L+255+114*(y-136),229)));
    for(let L=0;L<=255;L++)for(let y=0;y<BAND_LINES;y++)far[1].push(clamp(204+cdiv(114*(y-48)-256*L-255,229)));
    // what these windows and tiles show, against the browser's pixels for
    // a spread of radii and reaches (counted, not fixed)
    {
      let off=0,tot=0;
      const perR={};
      for(const[g,b]of BANDS.entries())for(const R of[4,8,12,16,20,24,28,30,34,40,48])for(const L of[20,60,100,140,196]){
        const k=R/2-1;
        for(let y=0;y<BAND_LINES;y++){
          const lo=g?far[1][L*BAND_LINES+y]:origin[y],hi=g?origin[BAND_LINES+y]:far[0][L*BAND_LINES+y];
          for(let x=0;x<256;x++){
            const ox=x-b.x,oy=y-b.y,u=(ox*b.vx+oy*b.vy)>>8,v=(-ox*b.vy+oy*b.vx)>>8,want=u>=0&&u<=L&&Math.abs(v)<=R;
            const i=(x>>3)+2*(y>>3),e=prof[(g*BAND_RS+k)*BAND_PROF+i],t=e&0x3ff,fl=!!(e&0xc000),d=(x&7)+2*(y&7);
            const got=x>=lo&&x<=hi&&tilePx(t,fl,d)!==0;
            if(want||got){tot++;if(want!==got){off++;perR[R]=(perR[R]??0)+1;}}
          }
        }
      }
      lines.push(`; band pixels off (sampled radii and reaches): ${off} of ${tot}; by radius ${JSON.stringify(perR)}`);
    }
    // each band's maps, rows 0-13 (row ty, column tx: profile entry tx +
    // 2 ty), one blob per band, radius-major: a whole map is one DMA
    const MAP_ROWS=14,mapSize=MAP_ROWS*32*2;
    for(const[g,b]of BANDS.entries()){
      const m=new Uint8Array(BAND_RS*mapSize);
      for(let k=0;k<BAND_RS;k++)for(let ty=0;ty<MAP_ROWS;ty++)for(let tx=0;tx<32;tx++){
        const w=prof[(g*BAND_RS+k)*BAND_PROF+tx+2*ty],o=k*mapSize+(ty*32+tx)*2;m[o]=w&255;m[o+1]=w>>8;
      }
      xdata(g?'orbit_band_maps_f':'orbit_band_maps_g',m);
    }
    const empty=new Uint8Array(BAND_LINES*2);empty.fill(0xff,0,BAND_LINES);
    xdata('orbit_bands',Uint8Array.from([...origin,...empty]));
    def('OB_LINES',BAND_LINES);def('OB_RS',BAND_RS);def('OB_MAP_SIZE',mapSize);
    def('OB_ORIGIN',0);def('OB_EMPTY',origin.length);
    // far cuts: Goku's in two blobs (reach 0-299, 300-360), Frieza's (0-255)
    xdata('orbit_cut_g0',Uint8Array.from(far[0].slice(0,300*BAND_LINES)));
    xdata('orbit_cut_g1',Uint8Array.from(far[0].slice(300*BAND_LINES)));
    xdata('orbit_cut_f',Uint8Array.from(far[1]));
    // star culling: To1, To2 per band and radius (words, band-major)
    lines.push('; band outer thresholds To1, To2 per band and radius (words)','orbit_fn_bthr:');
    for(let i=0;i<thr.length;i+=4)lines.push(`\tdw ${thr[i]},${thr[i+3]}`);
  }
  // The descent (clashCamera's 'win' branch, victoryTiming.descent to
  // .return): the globe grows from the clash's wide view (114, 164, 56) to
  // (-15, 281, 230), past the fight's line tables (56-104, bank F7), and
  // the radius and centre change every frame, too often for the fight's
  // window builder. The camera is the same every time (it depends on the
  // clock alone), so the generator makes it all, in extended data:
  // per radius the descent shows, the M7A and M7D rows (orbit.mjs
  // lineTables, the fight's rule) it can show (line 0 or the rim's top to
  // line 195), a radius never split between blobs; per frame (identical
  // frames shared) the window rows of lines max(0, cy - R) to min(223,
  // cy + R): the disc and rim edges (cx - w .. cx + w, clamped; the centre
  // column goes negative near the end), each window blob with an empty
  // record for the lines above the globe. (The HDMA reads them to line
  // 195; the stars' culling to line 223, as the fight's blocks hold every
  // row.) Indexes (data bank): orbit_fn_desc per radius R, first row, M7A,
  // M7D, bank; orbit_fn_dwin per frame the window rows, their bank and
  // first line, the blob's empty record.
  {
    const ages=[],cams=new Map();
    for(let age=victoryTiming.descent;age<=victoryTiming.return;age++){
      const c=clashCamera({clash:{phase:'win',age,from:{camera:{x:114,y:164,r:56}}},camera:{x:114,y:164,r:56}});
      if(c.r<FIGHT_R0||c.r>230)throw Error('orbit-finale: descent radius '+c.r);
      ages.push(c);if(!cams.has(c.r))cams.set(c.r,[]);cams.get(c.r).push(c);
    }
    const DESC_R1=230;
    // line tables per radius
    const mblobs=[[]],mindex=[];let used=0;
    for(let r=FIGHT_R0;r<=DESC_R1;r++){
      const t=lineTables(r),R=t.R,list=cams.get(r)??[];
      let jlo=R,jhi=-R;
      for(const c of list){jlo=Math.min(jlo,Math.max(-R,-c.y));jhi=Math.max(jhi,Math.min(R,195-c.y));}
      if(!list.length||jhi<jlo){jlo=-R;jhi=-R;}
      const rows=jhi-jlo+1,bytes=rows*4;
      if(used+bytes>0x8000){mblobs.push([]);used=0;}
      const b=mblobs.length-1,base=used,blob=mblobs[b];
      const put=v=>blob.push(v&255,(v>>8)&255);
      for(let jj=jlo;jj<=jhi;jj++)put(t.m7a[jj+R]);
      for(let jj=jlo;jj<=jhi;jj++)put(t.m7d[jj+R]);
      used+=bytes;
      mindex.push({R,jlo,b,m7a:base,m7d:base+rows*2});
    }
    mblobs.forEach((b,k)=>xdata(`orbit_desc_${k}`,Uint8Array.from(b)));
    // window rows per frame: W1 = the disc (BG1 inside), W2 = the rim
    // (colour math in W1 XOR W2), as globe.asm's builder makes them
    const edges=(cx,w)=>{if(w===255)return[255,0];const L=cx-w,Rr=cx+w;if(Rr<0||L>255)return[255,0];return[Math.max(0,L),Math.min(255,Rr)];};
    const wblobs=[[255,0,255,0]],windex=[],seen=new Map();let wused=4,wempty=[0];
    for(const c of ages){
      const t=lineTables(c.r),R=t.R,top=Math.max(0,c.y-R),bot=Math.min(223,c.y+R);
      const rowsB=[];
      for(let y=top;y<=bot;y++){const a=Math.abs(y-c.y),ww=t.ww[a];rowsB.push(...edges(c.x,ww&255),...edges(c.x,ww>>8));}
      const key=rowsB.join(',')+'|'+top;
      if(seen.has(key)){windex.push(seen.get(key));continue;}
      if(wused+rowsB.length>0x8000){wblobs.push([255,0,255,0]);wused=4;wempty.push(0);}
      const b=wblobs.length-1,e={b,off:wused,top:Math.max(0,top)};
      wblobs[b].push(...rowsB);wused+=rowsB.length;
      seen.set(key,e);windex.push(e);
    }
    wblobs.forEach((b,k)=>xdata(`orbit_dwin_${k}`,Uint8Array.from(b)));
    def('FND_DESC_R0',FIGHT_R0);def('FND_DESC_R1',DESC_R1);
    const mbytes=mblobs.reduce((n,b)=>n+b.length,0),wbytes=wblobs.reduce((n,b)=>n+b.length,0);
    lines.push(`; the descent's line tables per radius ${FIGHT_R0}-${DESC_R1} (${mbytes} bytes in ${mblobs.length} blobs): R, first row, M7A, M7D, bank (words)`,'orbit_fn_desc:');
    const xm=b=>`!XDATA_ORBIT_DESC_${b}`,xw=b=>`!XDATA_ORBIT_DWIN_${b}`;
    for(const e of mindex)lines.push(`\tdw ${e.R},${e.jlo&0xffff},(${xm(e.b)}+${e.m7a})&$FFFF,(${xm(e.b)}+${e.m7d})&$FFFF,(${xm(e.b)})>>16`);
    lines.push(`; the descent's window rows per frame from FNT_V_DESCENT (${wbytes} bytes in ${wblobs.length} blobs, ${seen.size} distinct of ${ages.length}): rows, bank, first line, the blob's empty record (words)`,'orbit_fn_dwin:');
    for(const e of windex)lines.push(`\tdw (${xw(e.b)}+${e.off})&$FFFF,(${xw(e.b)})>>16,${e.top},(${xw(e.b)})&$FFFF`);
  }
  // frieza.js returnToFortress: the landing candidates around Goku, 8-pixel
  // steps within 128 each way, in the order the browser picks among them
  // (distance, then its push order, dy outer and dx inner: the sort is
  // stable): dx, dy words in extended data (scene.asm orbit_land_search).
  {
    const c=[];
    for(let dy=-128;dy<=128;dy+=8)for(let dx=-128;dx<=128;dx+=8)c.push({dx,dy,d:dx*dx+dy*dy});
    c.sort((a,b)=>a.d-b.d);
    const b=new Uint8Array(c.length*4);
    c.forEach((p,i)=>{b[i*4]=p.dx&255;b[i*4+1]=(p.dx>>8)&255;b[i*4+2]=p.dy&255;b[i*4+3]=(p.dy>>8)&255;});
    xdata('orbit_land',b);
    def('FND_LAND_N',c.length);
  }
  // boss-victory.js cues: the burst ages
  lines.push('; boss-victory.js burst ages (words)','orbit_fn_bursts:','\tdw '+bossVictoryTiming.bursts.join(', '));
  def('FNT_B_NBURSTS',bossVictoryTiming.bursts.length);
  // The orbital death (boss-rush-death.js bossRushDeathPose with state.orbit):
  // the clock, and per age of the fall (fall to fallen) the 0.16 fraction
  // q = ceil(u^2 65536): the cartridge's x = from + round(d q / 65536) for d
  // = target - from >= 0 (half up), from - round_down(|d| (q - 1) / 65536)
  // for d < 0 (half toward zero), as the browser's Math.round(from + d u^2);
  // the cell and its half size. The browser's doubles land a few exact
  // halves a hair off (counted below against bossRushDeathPose itself).
  // Before the fall the pose stands at 'from': column 29 (gold, before the
  // revert) or 33.
  {
    const {bossRushDeathTiming:dt,bossRushDeathPose}=await eng('boss-rush-death.js');
    for(const[k,v]of Object.entries(dt))def(`FND_${k.toUpperCase()}`,v);
    const rnd=(d,q)=>d>=0?(d*q+32768)>>16:-((-d*(q-1)+32767)>>16);
    const rows=[];let miss=0,checked=0;
    for(let age=dt.fall;age<dt.fallen;age++){
      const u=Math.max(0,Math.min(1,(age-dt.fall)/(dt.fallen-dt.fall))),q=Math.ceil(u*u*65536);
      const probe=(fx,fy,cx,cy,cr)=>bossRushDeathPose({age,gold:false,orbit:{camera:{x:cx,y:cy,r:cr},hero:{x:fx,y:fy}}});
      for(let fx=0;fx<256;fx+=17)for(const[cx,cy,cr]of[[95,154,104],[114,164,56],[99,150,84],[118,146,92]]){
        const fy=(fx*7)%224,p=probe(fx,fy,cx,cy,cr);
        const tx=cx+Math.floor(((fx-cx)*28+50)/100),ty=Math.min(192,cy+Math.floor((cr+2)/4));
        if(Math.round(cx+(fx-cx)*.28)!==tx||Math.min(192,Math.round(cy+cr*.25))!==ty)throw Error('orbit-finale: the fall target differs');
        checked+=2;if(p.x!==fx+rnd(tx-fx,q))miss++;if(p.y!==fy+rnd(ty-fy,q))miss++;
      }
      const pose=probe(156,155,95,154,104),size=pose.size,column=pose.column;
      if(column<48||column>51)throw Error('orbit-finale: fall column '+column);
      const cell=size===16?`!OSP_GOKU_FALL_${column}`:column===51?`!OSP_GOKU_FALL_51_${size}`:null;
      if(!cell)throw Error(`orbit-finale: no fall cell for column ${column} at ${size} px`);
      rows.push(`\tdw ${q},${cell},${size/2}`);
    }
    if(miss>checked/200)throw Error(`orbit-finale: the fall misses ${miss} of ${checked} browser pixels`);
    lines.push(`; the orbital death's fall per age from FND_FALL: q (0.16), cell, half size (words); ${miss} of ${checked} sampled browser pixels one off`,'orbit_fn_fall:',...rows);
  }

  writeFileSync(join(outDir,'finale.asm'),lines.join('\n')+'\n');
}
