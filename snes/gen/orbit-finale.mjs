// Orbit finale data: the beam struggle's clock (engine/frieza-finale.js
// tickClash / tapClash / clashCamera / descentPose) and the victory beat
// (frieza.js won stage, boss-victory.js), as tables the cartridge reads.
//
// Single source of truth: timings come from the browser's exported
// clashTiming, clashSurges, victoryTiming and bossVictoryTiming. The
// struggle's pressure is a double in the browser; the cartridge keeps it
// in Q31 fixed point (1.0 = 2^31), so every constant here is the browser's
// literal rounded once, and the per-frame decay (.0012 + .0014 * min(1,
// age / 720)) is tabulated per age from the browser's own expression. The
// eases (t^2 (3 - 2t)) are tabulated per frame as 32-bit fractions, so
// Math.round(a + (b - a) * t) can be reproduced exactly for the integer
// mixes the browser's state depends on.
//
// Outputs (dist/snes/gen/orbit-finale/finale.asm): defines (!FNT_*,
// !FNQ_*), the decay table and the ease tables; module.asm includes it in
// its !DATA_ORBIT block.
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';

const Q31=2**31;
const q31=v=>Math.round(v*Q31);
const hexd=v=>'$'+(v>>>0).toString(16).padStart(8,'0');

// The bands above the globe (fdraw.asm bands): the clash's rays all start
// from Goku at (28, 136) (heading 15) or Frieza at (204, 48) (heading 7).
export const BANDS=[{name:'blue',x:28,y:136,vx:229,vy:-114,pal:7},{name:'purple',x:204,y:48,vx:-229,vy:114,pal:1}];
export const BAND_LINES=106,BAND_RS=24;    // rows 0-105; radii 2, 4, ... 48
const BAND_PROF=58;                        // map profile entries (tile x + 2 * tile y)

export async function generate({repo,outDir,xdata}){
  const eng=f=>import(pathToFileURL(join(repo,'engine',f)).href);
  const {clashTiming,clashSurges,victoryTiming,ease,descentPose}=await eng('frieza-finale.js');
  const {orbitHeading}=await eng('orbit-pixels.js');
  const {bossVictoryTiming}=await eng('boss-victory.js');
  const lines=['; Generated by snes/gen/orbit-finale.mjs (do not edit)'];
  const def=(k,v)=>lines.push(`!${k} = ${v}`);
  for(const[k,v]of Object.entries(clashTiming))def(`FNT_${k.toUpperCase()}`,v);
  for(const[k,v]of Object.entries(victoryTiming))def(`FNT_V_${k.toUpperCase()}`,v);
  for(const[k,v]of Object.entries(bossVictoryTiming))if(typeof v==='number')def(`FNT_B_${k.toUpperCase()}`,v);
  clashSurges.forEach((s,i)=>{def(`FNT_SURGE${i}`,s.at);});
  if(clashSurges.length!==3)throw Error('orbit-finale: three surges expected');
  // tickClash / tapClash literals (Q31). The browser's products are taken
  // as the doubles it computes (.036 * .65).
  const Q={P0:.43,CAP:.92,ONE:1,WIN:.975,FAIL:.04,DOWN:.006,UP:.004,TAP:.036,TAPS:.036*.65};
  for(const[k,v]of Object.entries(Q))def(`FNQ_${k}`,q31(v));
  lines.push('; surge losses (Q31 dwords)','orbit_fn_loss:','\tdd '+clashSurges.map(s=>q31(s.loss)).join(', '));
  lines.push('; surge start ages (words)','orbit_fn_surge_at:','\tdw '+clashSurges.map(s=>s.at).join(', '));
  // Per-frame decay, ages 0..720 (later ages use the last entry).
  const decay=[];for(let a=0;a<=720;a++)decay.push(q31(.0012+.0014*Math.min(1,a/720)));
  lines.push('; struggle decay per age (Q31 dwords, 721)','orbit_fn_decay:');
  for(let i=0;i<decay.length;i+=8)lines.push('\tdd '+decay.slice(i,i+8).map(hexd).join(','));
  // Eases as 32-bit fractions; exactly 1 is $FFFFFFFF (mix returns b).
  const frac=t=>t>=1?0xffffffff:Math.min(0xfffffffe,Math.round(t*2**32));
  const table=(name,n,note)=>{
    const v=[];for(let a=0;a<=n;a++)v.push(frac(ease(a/n)));
    lines.push(`; ${note}: ease(age / ${n}), ages 0..${n} (dwords)`,`${name}:`);
    for(let i=0;i<v.length;i+=8)lines.push('\tdd '+v.slice(i,i+8).map(hexd).join(','));
  };
  table('orbit_fn_e110',110,'gather positions');
  table('orbit_fn_e150',clashTiming.gather,'gather camera');
  table('orbit_fn_e240',victoryTiming.return-victoryTiming.descent,'descent camera');
  // The finale view's rays and poses (frieza-finale-view.js) depend only on
  // the phase age once the gather has put Goku at (28, 136) and Frieza at
  // (204, 48): what fx.beam draws for each (rounded ends, the quantised
  // heading, reach = min(360, length), band radius max(2, round(width / 2)
  // * 2); no band below width 1), per age.
  const H={x:28,y:136},B={x:204,y:48},DX=B.x-H.x,DY=B.y-H.y,N=Math.hypot(DX,DY);
  const point=t=>({x:H.x+DX*t,y:H.y+DY*t});
  const ray=(x,y,xx,yy,width)=>{
    if(width<1)return{R:0,length:0,heading:0};
    x=Math.round(x);y=Math.round(y);xx=Math.round(xx);yy=Math.round(yy);
    const length=Math.round(Math.hypot(xx-x,yy-y));
    return{R:Math.max(2,Math.round(width/2)*2),length:Math.min(360,length),heading:orbitHeading(xx-x,yy-y)};
  };
  const words=(name,note,v)=>{lines.push(`; ${note}`,`${name}:`);for(let i=0;i<v.length;i+=12)lines.push('\tdw '+v.slice(i,i+12).join(','));};
  {
    const v=[];
    for(let a=0;a<=clashTiming.launch;a++){const t=ease(a/clashTiming.contact),f=point(.43*t),e=point(1-.57*t),b=ray(H.x,H.y,f.x,f.y,27),p=ray(B.x,B.y,e.x,e.y,30);v.push(b.length,b.heading,p.length,p.heading);}
    words('orbit_fn_launch','launch: blue length, heading, purple length, heading per age (bands 28 and 30)',v);
  }
  {
    const v=[];
    for(let a=0;a<32;a++){const p=point(Math.max(0,.12-a/100)),r=ray(B.x,B.y,p.x,p.y,34*(1-a/40));v.push(r.R,r.length,r.heading);}
    words('orbit_fn_recoil','recoil: purple band radius, length, heading per age 0-31',v);
    const g=[];for(let a=0;a<=clashTiming.recoil;a++)g.push(Math.round(6*Math.sin(Math.PI*Math.min(1,a/clashTiming.recoil))));
    words('orbit_fn_recoil_dx','recoil: Goku pushed back (pixels) per age',g);
  }
  {
    const v=[];
    for(let a=0;a<victoryTiming.beamEnd;a++){
      const grow=ease(a/65),tail=1-ease((a-victoryTiming.beamFade)/(victoryTiming.beamEnd-victoryTiming.beamFade));
      const length=N+grow*260,width=(30+grow*15)*tail,r=ray(H.x,H.y,H.x+DX/N*length,H.y+DY/N*length,width);v.push(r.R,r.length,r.heading);
    }
    words('orbit_fn_win','victory beam: band radius, length, heading per age',v);
  }
  {
    const v=[];
    for(let age=victoryTiming.descent;age<victoryTiming.return;age++){
      const o={hero:{...H},camera:{x:0,y:0,r:0},clash:{phase:'win',age,from:{camera:{x:0,y:0,r:0}}}};
      const p=descentPose(o,age),size=Math.max(16,Math.round(p.size/8)*8);
      v.push(Math.round(p.x)-size/2,Math.round(p.y)-size/2,size);
    }
    words('orbit_fn_descent','descent: Goku\'s top left x, y and size per age from the descent',v);
  }
  {
    const v=[];
    for(let a=victoryTiming.reward;a<victoryTiming.acquire;a++){const p=point(1-ease((a-victoryTiming.reward)/(victoryTiming.acquire-victoryTiming.reward)));v.push(Math.round(p.x),Math.round(p.y));}
    words('orbit_fn_pouch','pouch: centre x, y per age from the reward',v);
  }
  // Beam bands above the globe: per band and radius, each row's band extent
  // (|v| <= R and u >= 0, exactly as orbit-effects.js tests each pixel; the
  // far end is cut at run time), and the BG map profile of its inner half:
  // the inner/outer edges x + 2y = T1, T2 fitted to the browser's pixels
  // (the edge's true slope is -114/229, half a pixel off -1/2 across the
  // screen), as entries of the band tiles (orbit-fx.mjs band.bin).
  {
    const stat=[],prof=[];
    for(const b of BANDS){
      const st=[],pr=[];
      for(let k=0;k<BAND_RS;k++){
        const R=2+k*2,hist=[0,0,0].map(()=>new Int32Array(512));
        for(let y=0;y<BAND_LINES;y++){
          let lo=999,hi=-999;
          for(let x=0;x<256;x++){
            const ox=x-b.x,oy=y-b.y,u=(ox*b.vx+oy*b.vy)>>8,v=(-ox*b.vy+oy*b.vx)>>8;
            if(u<0||Math.abs(v)>R)continue;
            if(x<lo)lo=x;if(x>hi)hi=x;
            const idx=Math.min(3,Math.floor((v+R)*4/(2*R+1)));
            hist[idx===1||idx===2?1:idx===0?0:2][x+2*y]++;
          }
          // the static extent; contiguous by construction (two half planes)
          st.push(...(lo<=hi?[lo,hi]:[0xff,0]));
        }
        // T1, T2: fewest pixels on the wrong side (outer for d < T1 and
        // d >= T2, inner between)
        const inner=hist[1],outer=hist[0].map((c,i)=>c+hist[2][i]),cumI=[0],cumO=[0];
        for(let d=0;d<512;d++){cumI.push(cumI[d]+inner[d]);cumO.push(cumO[d]+outer[d]);}
        let best=Infinity,T1=0,T2=0;
        for(let t1=0;t1<=511;t1++)for(let t2=t1;t2<=512;t2++){
          const e=cumI[t1]+(cumO[t2]-cumO[t1])+(cumI[512]-cumI[t2]);
          if(e<best){best=e;T1=t1;T2=t2;}
        }
        for(let i=0;i<BAND_PROF;i++){
          const c1=T1-8*i,c2=T2-8*i;
          let t;
          if(c2<=0||c1>=22)t=0;                       // outer
          else if(c1<=0&&c2>=22)t=1;                  // inner
          else if(c1>=1&&c2>=22)t=2+c1-1;             // outer, then inner
          else if(c1<=0)t=23+c2-1;                    // inner, then outer
          else{                                       // a thin inner half: the nearer edge
            let below=0,above=0;for(let py=0;py<8;py++)for(let px=0;px<8;px++){const d=px+2*py;if(d<c1)below++;if(d>=c2)above++;}
            t=above<=below?2+c1-1:23+c2-1;
          }
          pr.push(t|(b.pal<<10));
        }
        lines.push(`; band ${b.name} R ${R}: T1 ${T1} T2 ${T2}, ${best} of the inner/outer pixels off`);
      }
      stat.push(...st);prof.push(...pr);
      b.statBytes=st;b.profWords=pr;
    }
    const bytes=new Uint8Array(BANDS.length*BAND_RS*(BAND_LINES*2+BAND_PROF*2));
    let at=0;
    for(const b of BANDS){bytes.set(b.statBytes,at);at+=b.statBytes.length;for(const w of b.profWords){bytes[at++]=w&255;bytes[at++]=w>>8;}}
    xdata('orbit_bands',bytes);
    def('OB_LINES',BAND_LINES);def('OB_RS',BAND_RS);def('OB_PROF',BAND_PROF);
    def('OB_STAT_SIZE',BAND_LINES*2);def('OB_PROF_SIZE',BAND_PROF*2);
    def('OB_BAND_SIZE',BAND_RS*(BAND_LINES*2+BAND_PROF*2));
    def('OB_PROF_AT',BAND_RS*BAND_LINES*2);
  }
  // boss-victory.js cues: the burst ages
  lines.push('; boss-victory.js burst ages (words)','orbit_fn_bursts:','\tdw '+bossVictoryTiming.bursts.join(', '));
  def('FNT_B_NBURSTS',bossVictoryTiming.bursts.length);
  writeFileSync(join(outDir,'finale.asm'),lines.join('\n')+'\n');
}
