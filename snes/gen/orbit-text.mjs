// Orbit text panels: the orbit intro's five lines, Luna's remark, the beam
// struggle's prompts and Frieza's surges (frieza-orbit-view.js textPanel).
//
// Single source of truth: every message is rendered by the browser's own
// engine/native-radio.js radioPixels (the retail window tiles and 8x12 font
// read from the ROM) from the browser's strings (frieza-cinematic.js,
// frieza-finale.js; Luna's line is read out of orbit-debris.js), exactly at
// the browser's screen position (8, 8). The 240x64 picture is cut into 8x8
// BG3 tiles (2bpp), deduplicated across all messages: frame tiles use BG3
// palette 1 (window black, grey, white), interior tiles palette 2 (the
// dither, the black outline, the white text). Name codes show the retail
// default names (native-names.js defaultNames).
//
// Outputs (dist/snes/gen/orbit-text/):
//   tiles.bin  BG3 tiles (16 bytes each), loaded at BG3 tile !OTXT_TILE0
//   text.asm   palettes, one 30 x 8 map per message (BG3 entries: tile,
//              palette, priority), message defines
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';

export const OTXT_TILE0=0x180;     // free BG3 tiles $180-$1FF in the orbit
const hex4=v=>'$'+(v&0xffff).toString(16).padStart(4,'0');

export async function generate({rom,repo,outDir}){
  const eng=f=>import(pathToFileURL(join(repo,'engine',f)).href);
  const {radioPixels}=await eng('native-radio.js');
  const {orbitIntroLines}=await eng('frieza-cinematic.js');
  const {clashLines,clashSurges}=await eng('frieza-finale.js');
  const {defaultNames}=await eng('native-names.js');
  const debris=readFileSync(join(repo,'engine/orbit-debris.js'),'utf8');
  const luna=debris.match(/aside=\{text:'((?:[^'\\]|\\.)*)'/);
  if(!luna)throw Error('orbit-text: Luna\'s remark not found in orbit-debris.js');
  const glyph=b=>b>=0x81&&b<=0x9a?String.fromCharCode(b-32):b>=0x9b&&b<=0xb4?String.fromCharCode(b-90):'';
  const names=t=>t.replace(/\{([0-3])\}/g,(_,n)=>n==='0'?'GOKU':defaultNames[n].map(glyph).join(''));
  const messages=[
    ...orbitIntroLines.map((t,i)=>[`INTRO${i+1}`,t]),
    ['LUNA',luna[1].replace(/\\n/g,'\n').replace(/\\'/g,"'")],
    ...Object.entries(clashLines).map(([k,t])=>[k.toUpperCase(),t]),
    ...clashSurges.map((s,i)=>[`SURGE${i+1}`,s.text]),
  ];
  // Colours: frame (window tiles) and interior (dither, outline, text).
  const frame=[0x0000,0x5250,0x739c],inner=[0x2c00,0x0000,0x7fff];
  const tiles=[],index=new Map(),maps=[];
  for(const[name,text]of messages){
    const px=radioPixels(rom,names(text)),map=[];
    for(let ty=0;ty<8;ty++)for(let tx=0;tx<30;tx++){
      const border=ty===0||ty===7||tx===0||tx===29,pal=border?frame:inner;
      const bytes=new Uint8Array(16);let any=false;
      for(let y=0;y<8;y++)for(let x=0;x<8;x++){
        const v=px[(ty*8+y)*240+tx*8+x];if(!v)continue;
        const c=pal.indexOf(v-1);if(c<0)throw Error(`orbit-text: colour ${(v-1).toString(16)} in a ${border?'frame':'text'} tile of ${name}`);
        const i=c+1;any=true;
        if(i&1)bytes[y*2]|=0x80>>x;if(i&2)bytes[y*2+1]|=0x80>>x;
      }
      if(!any){map.push(0);continue;}
      const key=(border?'f':'i')+Buffer.from(bytes).toString('hex');
      let t=index.get(key);if(t===undefined){t=tiles.length;tiles.push(bytes);index.set(key,t);}
      // BG3 entry: tile, palette 1 (frame) or 2 (text), priority (above all in Mode 1 + BG3 priority)
      map.push((OTXT_TILE0+t)|((border?1:2)<<10)|0x2000);
    }
    maps.push([name,map]);
  }
  if(tiles.length>128)throw Error(`orbit-text: ${tiles.length} tiles for 128 free BG3 tiles`);
  const bin=new Uint8Array(tiles.length*16);tiles.forEach((b,i)=>bin.set(b,i*16));
  writeFileSync(join(outDir,'tiles.bin'),bin);
  const L=['; Generated by snes/gen/orbit-text.mjs - do not edit.',`!OTXT_TILE0 = $${OTXT_TILE0.toString(16)}`,`!OTXT_TILES = ${tiles.length}`];
  maps.forEach(([name],i)=>L.push(`!OTXT_${name} = ${i+1}`));
  L.push(`!OTXT_COUNT = ${maps.length}`);
  L.push('orbit_text_pal:','\tdw '+[0,...frame,0,...inner].map(hex4).join(','));
  L.push('orbit_text_maps:');
  for(const[name,map]of maps){L.push(`; ${name}`);for(let r=0;r<8;r++)L.push('\tdw '+map.slice(r*30,r*30+30).map(hex4).join(','));}
  writeFileSync(join(outDir,'text.asm'),L.join('\n')+'\n');
}
