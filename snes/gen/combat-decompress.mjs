// Predecode the Hydra's large native WRAM graphics stream. The retail
// bit decoder at C2:24F1 takes several video frames for this fixed asset;
// the hook in core/native.asm jumps to this FastROM copy and retains the
// original decoder for every other stream.
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {hiromToPc} from '../tools/w65816.mjs';

export async function generate({rom,outDir,xdata}){
  const source=hiromToPc(0xDBD989,rom.length),count=2048;
  let src=source,prev=0,older=0,shifted=0;
  const out=new Uint8Array(count+1);
  for(let group=0;group<count;group+=8){
    shifted=rom[src+1]<<8;
    let flags=rom[src++];
    for(let bit=0;bit<8;bit++){
      const value=flags&0x80?rom[src++]|(rom[src]<<8):older;
      // X/Y are eight-bit here: STY $6C replaces only its low byte.
      older=(older&0xFF00)|(prev&255);prev=value;
      out[group+bit]=value&255;
      out[group+bit+1]=value>>8;
      flags=(flags<<1)&255;
    }
  }
  if(src-source!==0x4B6||prev!==0x00C0||older!==0x00C0)
    throw Error(`Hydra decoder changed: source +${(src-source).toString(16)}, history ${older.toString(16)}/${prev.toString(16)}`);
  xdata('COMBAT_HYDRA_GRAPHICS',out);
  const asm=['; Generated by snes/gen/combat-decompress.mjs.','combat_native_hydra_copy:'];
  for(let offset=0;offset<count;offset+=2){
    asm.push(`\tLDA.l !XDATA_COMBAT_HYDRA_GRAPHICS+${offset}`);
    asm.push(`\tSTA.l $7F${(0x7000+offset).toString(16).toUpperCase().padStart(4,'0')}`);
  }
  asm.push(
    '\tSEP #$20','\tLDA.l !XDATA_COMBAT_HYDRA_GRAPHICS+2048','\tSTA.l $7F7800','\tREP #$20',
    '\tLDA.w #$DE3F','\tSTA $79','\tLDA.w #$7800','\tSTA $7C',
    '\tLDA.w #$00C0','\tSTA $6A','\tSTA $6C','\tTAY','\tLDX.w #0',
    `\tLDA.w #$${shifted.toString(16).toUpperCase().padStart(4,'0')}`,'\tSTA $6E',
    '\tLDA.w #1','\tSTA $68','\tLDA.w #$7800','\tCMP.w #$4000','\tDEC $68','\tREP #$10','\tJML $C22533',
  );
  writeFileSync(join(outDir,'copy.asm'),asm.join('\n')+'\n');
}
